def make_vault(
    tmp_path: Path, board: str, concepts: list[str], seed_files: dict[str, str], extra_nodes: list[str] = ()
) -> Path:
    vault = tmp_path / "vault"
    for d in ("原白板", "节点", "检验白板", "outputs"):
        (vault / d).mkdir(parents=True, exist_ok=True)
    lines = "\n".join(f"- {c}" for c in concepts)
    (vault / "原白板" / f"{board}.md").write_text(
        BOARD_SCAFFOLD.format(board=board, concepts=lines, n=len(concepts)), encoding="utf-8"
    )
    for name, body in seed_files.items():
        (vault / "节点" / f"{name}.md").write_text(body, encoding="utf-8")
    for name in extra_nodes:
        (vault / "节点" / f"{name}.md").write_text(f"# {name}\n", encoding="utf-8")
    return vault



class TestReadOnly:
    def test_vault_untouched_when_outdir_external(self, tmp_path):
        vault = make_vault(
            tmp_path,
            "板A",
            concepts=["[[节点/种子]] — 种子 · 掌握度 — · 未考"],
            seed_files={"种子": SEED_RICH.format(board="板A")},
        )

        def snapshot(root: Path) -> dict:
            # v3 (Codex 三轮): 文件 bytes+mtime+mode + 目录集合含 mtime_ns+mode + vault 根本体
            entries = {"<root>": ("d", root.lstat().st_mtime_ns, root.lstat().st_mode)}
            for p in sorted(root.rglob("*")):
                st = p.lstat()
                if p.is_file() and not p.is_symlink():
                    entries[str(p.relative_to(root))] = ("f", st.st_mtime_ns, st.st_mode, p.read_bytes())
                else:
                    entries[str(p.relative_to(root))] = ("d/l", st.st_mtime_ns, st.st_mode)
            return entries

        before = snapshot(vault)
        out = tmp_path / "external-out"
        assert run_cli(vault, "板A", out).returncode == 0
        assert snapshot(vault) == before, "vault 内任何文件/目录 (含 mtime/mode) 不得被触碰"
        produced = sorted(p.name for p in out.iterdir())
        assert produced == ["split-preview-板A.json", "split-preview-板A.md"]


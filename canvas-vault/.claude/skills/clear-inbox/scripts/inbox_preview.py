_AI_MARKERS_NORM = tuple(" ".join(m.split()).casefold() for m in AI_MARKERS)

#: ⛔ 护栏级 AI 信号（结构性，不依赖枚举表）：文本含独立「AI」字样即算嫌疑。
#: 「独立」= 左右都**不是 ASCII 字母**（`\bAI\b` 在 CJK 邻接时无词边界 ——
#: round-7 BLOCKER-1：`由AI系统生成` 曾穿透）。有限标记表无论怎么扩都追不上
#: 自然语言的肯定式声明（round-6 BLOCKER-1：`This report was generated by an
#: AI system` 不含任何表项，双层全盲，无正文时掉进 C3 建议删）。本信号只降
#: C6 不裁决 —— C2 确定命中仍走有限表 + 边界规则（宽匹配会给话题提及发确定
#: 归档，那是硬猜）。
_AI_WORD_RE = re.compile(r"(?<![A-Za-z])AI(?![A-Za-z])", re.IGNORECASE)

#: ⛔ 护栏级**生成断言结构**（round-8 BLOCKER-2）：`generator: 由 GPT-4 生成`
#: 里既没有表项（表只收到 `由 GPT 生成`，`GPT-4` 差一个版本号）也没有独立词
#: 「AI」，三层护栏全盲 → 无正文时掉进 C3 `建议删 + confident=true`。
#: 修法按**声明骨架**而不是**枚举模型名**（卡文 §3 默认裁决）：模型名是开放
#: 集合，`GPT-4` 之后还有 `GPT-4o`/`Claude 3.5`/`Gemini 2.5`/下个月发布的那个，
#: 枚举永远追不上；「由 <某物> 生成」这个断言骨架是闭合的。
#: ⚠️ 只作**未消化信号降 C6**，绝不进 C2：宽匹配给话题提及发确定归档就是硬猜
#: （`由编译器生成`、`generated by hand` 都会命中本条 —— 它们降 C6，方向安全）。
#: 中文：`由` 与 `生成` 之间任意个**非句读**字符（句读收尾防跨句吞成假断言）。
#: ⛔ round-2 审查 BLOCKER：原先写 `{1,40}?` 加了长度上界，于是
#: `本文由 openai-gpt-oss-120b-finetune-canvas-learning-system-v2026-09-01 生成`
#: （中间 65 字符）穿透 —— **上界本身就是缝隙**，而当初说「断言骨架是闭合的」
#: 正因为这个上界而不成立。去掉上界后骨架才真的闭合（同一行、中间不跨句读）。
#: 放宽的代价是 `由于…最终生成了报告` 这类也会命中，但那只降 C6（拿不准、不删），
#: 误命中方向安全 —— 用一点召回换掉一条确定删除的路径，是划算的。
_GEN_CLAIM_CN_RE = re.compile(r"由[^。；！？\n]*?生成")
#: 英文：在归一（连续空白折叠为单空格 + casefold）后的行上匹配，故只写单空格。
#: ⛔ round-2 审查 BLOCKER：原先写 `generated by \S`（字面空格 + 非空），于是
#: `Generated by: GPT-4` 穿透 —— `by` 后面是冒号不是空格。改为 `by` 词边界后
#: 允许任意非词字符（冒号/破折号/空格）再要求一个词字符：
#: ⛔ round-3 审查 HIGH：上一版写 `generated by\b\W*\w`，而 `_` 属于 `\w` ——
#: `Generated by_GPT-4` 的 `by` 与 `_` 之间**没有**词边界，整条穿透（C3 与 C4
#: 两个出口都中）。词边界这个概念在这里本来就不对：要判的是「by 是不是一个
#: 完整的词」，直接写成「后面不是字母数字」才准确，分隔符则连下划线一起吃。
#:   `generated by: gpt-4` ✅ / `generated by llama` ✅ / `generated by_gpt-4` ✅
#:   / `generated byte` ❌（by 后面是字母）/ 行尾 `generated by` ❌（没有主语）
_GEN_CLAIM_EN_RE = re.compile(r"generated by(?![^\W_])[\W_]*[^\W_]")

#: ⛔ 护栏级**生成器声明字段**（round-8 BLOCKER-2 的另一半）：键名本身就是声明。
#: `generator: gpt-4`（值里没有「生成」二字）只有本条能接住，`本文由 GPT-4 生成`
#: 写在正文里（无 frontmatter）只有 `_GEN_CLAIM_*` 能接住 —— 两条互补，都不冗余。
#: 键名归一口径见 `_norm_fm_key`。
_GENERATOR_DECL_KEYS = frozenset(
    {"generator", "generated_by", "ai_generated", "model", "llm", "ai"}
)

#: ⛔ 来源声明键别名（round-8 HIGH）：`Source: DOI:10.1000/xyz` 的唯一来源标识
#: 曾被当作不存在 —— `"source" in fm` 是**大小写敏感**的字面查找，取不到 `Source`；
#: 而值不含 `http(s)://`，`url_bearing_keys` 也接不住。⚠️ 本别名集合只用于
#: **护栏**：C1 仍只认字面小写 `source` 键（R8 稿约定），DOI 更不冒充 URL 或 C1
#: （卡文 §3 默认裁决）—— 信号只把来源摆上台面降 C6，不给出「留原地/一手」提名。
_SOURCE_DECL_KEYS = frozenset({"source", "sources"})

#: ⛔ C3「空骨架」的兜底口径**两轮才收敛到位**，过程记在这里以免后人重走：
#:
#: round-2 审查 HIGH 先逼出**方向反转**：此前所有来源护栏都在枚举「危险的键名和
#: 值形态」（source/url/doi…），那是 fail-open —— 漏一个就是一条确定删除的路径，
#: 而 `citation: ISBN 978-7-111-54742-6` 正好两样都不沾，被判 C3 确定删除。
#: 于是改成枚举「已知无害、删掉不丢信息」的键名白名单，默认拦住。
#:
#: round-3 审查 HIGH 又把那份白名单打穿：**放行的是键名，可信息在值里**。
#: `title: ISBN 978-…`、`aliases: <馆藏号>`、`title: <这份材料仅有的那句话>`
#: 全都因为键名在白名单而被判 C3 确定删除；C4 侧更直接 —— 引擎自己挂着
#: 「正文重复证据不覆盖这些元数据」的冲突，却仍然 confident=true。
#: **「这个键名无害」是个无法机械成立的断言**：`title` 可能是一句 t，也可能是
#: 这份材料唯一写下来的东西，引擎分不出来，分不出来就不能替用户决定。
#:
#: 现口径（信号⑨）：**frontmatter 里只要有任何非空值，C3/C4 就不确定删除**。
#: 白名单整个取消 —— 不是收窄，是这条路本身走不通。
#: ⚠️ 代价如实说：C3 的可达面明显变窄，只剩「0 字节」「没有 frontmatter 的纯
#: 骨架」「frontmatter 全是空值」三种。这是刻意选的偏向 —— 少删一份的代价是
#: 用户多看一眼，多删一份的代价是材料没了。
#: 依据是卡文 §3 默认裁决「未知结构或来源信号至少降级 C6」。

#: DOI 形态（ISO 26324：`10.<registrant>/<suffix>`）。左界排除字母数字与点，
#: 于是 `DOI:10.1000/xyz`、`doi: 10.1000/xyz`、裸 `10.1000/xyz` 都命中，而
#: 版本号 `v10.1000/x` 之类不命中。⚠️ 只作来源信号，不解析、不解引用、不联网。
_DOI_RE = re.compile(r"(?<![0-9A-Za-z.])10\.\d{4,9}/[^\s\"'<>]+")


def _norm_fm_key(k: str) -> str:
    """frontmatter 键名归一：casefold + `-`→`_`。

    ⛔ 仅供**护栏**的键名比对（`Source`/`SOURCE`/`generated-by` 与
    `source`/`generated_by` 同判）。判据侧（C1）刻意不走这里 —— 那会静默扩大
    C1 的命中面，而 C1 命中意味着「一手来源 · 留原地 · confident=true」，
    是有后果的提名，扩它必须是明写的决定而不是归一化的副作用。
    """
    return k.casefold().replace("-", "_")


#: ISBN-10 / ISBN-13：`ISBN` 前缀（可选）+ 9-13 位数字/连字符，末位可为 X。
#: ⛔ 与 DOI 同源的**正面形态**判定，不是枚举关键词：ISBN 有固定位数与校验位，
#: 这是它「像个标识符」的结构证据。用于文件名与值两处来源信号。
_ISBN_RE = re.compile(
    r"(?<![0-9A-Za-z])(?:ISBN[-\s_:]*)?(?=[\d-]{9,17}[\dXx](?![\d-]))[\d-]{9,17}[\dXx]",
    re.IGNORECASE,
)


def _looks_like_isbn_value(v: str) -> bool:
    """值/文件名里含 ISBN 形态的标识符（非空才算）。"""
    if not v:
        return False
    m = _ISBN_RE.search(v)
    if not m:
        return False
    digits = [c for c in m.group(0) if c.isdigit() or c in "Xx"]
    return len(digits) in (10, 13)


def _looks_like_doi_value(v: str) -> bool:
    """值里含 DOI 形态的来源标识（⛔ substring 级，与 `_looks_like_source_value`
    同口径）。非空才算 —— 卡文 (d) 要的是「**非空** DOI 来源阻止 C3 删除」。"""
    return bool(v) and bool(_DOI_RE.search(v))


def find_generation_claim(text: str) -> str | None:
    """文头窗口内的**生成断言结构**片段（归一化匹配），无则 None。

    ⛔ 只作 C3/C4 的「未消化信号」，不作 C2 判据 —— 见 `_GEN_CLAIM_CN_RE` 头注。
    返回归一化后的命中片段（casefold + 空白折叠），供 uncertain_reason 展示；
    ⚠️ 它是**归一形态**不是输入原文，措辞里如实这么说（round-8 §四对
    「basis 带逐字片段」的证伪同源教训：写「逐字」就必须真的逐字）。
    """
    for _, ln in head_window(text):
        for norm in _guard_variants(ln):
            for rx in (_GEN_CLAIM_CN_RE, _GEN_CLAIM_EN_RE):
                m = rx.search(norm)
                if not m:
                    continue
                # ⛔ round-2 审查 LOW：英文骨架以单个词字符收尾，直接 group(0) 只给到
                # `generated by l` —— 人工核对时看不出是哪个模型。补到该词结束。
                end = m.end()
                while end < len(norm) and (norm[end].isalnum() or norm[end] in "-_.:"):
                    end += 1
                return norm[m.start() : end]
    return None


def _find_marker_pos(ln: str, marker: str) -> int:
    """marker 在**已归一**的 ln 中第一个满足右边界规则的起点；无则 -1。

    ⛔ 右边界 = 行尾、空白或 `_MARKER_BOUNDARY_PUNCT` 标点（round-2 H2）：裸子串
    匹配曾把 `# 由 AI 生成内容的版权问题` 这类话题提及判成 AI 自述并给出确定的
    归档去向。同一行里前一处命中不满足边界时继续向后找 —— 不因首处被拒就漏掉
    行内更靠后的真命中。
    ⛔ 以 ASCII 字母收尾的标记（`Generated by AI`）右边界**不含空白**：中英混排里
    ASCII 词后天然是空格，放行空白等于边界规则对这些标记是空操作 ——
    `Generated by AI Lab researchers` 会被误判成 AI 自述（round-3 自审 H2-1）。
    只认行尾或标点；漏判方向落 C6，安全。"""
    ascii_ending = marker[-1].isascii() and marker[-1].isalpha()
    start = 0
    while (i := ln.find(marker, start)) >= 0:
        j = i + len(marker)
        if j >= len(ln) or ln[j] in _MARKER_BOUNDARY_PUNCT:
            return i
        if not ascii_ending and ln[j].isspace():
            return i
        start = i + 1
    return -1


def find_ai_marker(text: str) -> tuple[int, str] | None:
    """文头窗口内的 AI 标记（归一化匹配：大小写/空白变体不漏，round-5 BLOCKER-1；
    右边界规则见 `_find_marker_pos`）。同行多命中时取「最靠前、同位置取最长」。
    ⛔ 返回的 marker 是**原表原文**（供 basis 逐字展示），匹配在归一化形态上做
    —— 行号准确，文本保真。"""
    for lineno, ln in head_window(text):
        norm = _norm_ai_line(ln)
        hits = [
            (pos, -len(nm), orig)
            for nm, orig in zip(_AI_MARKERS_NORM, AI_MARKERS)
            if (pos := _find_marker_pos(norm, nm)) >= 0
        ]
        if hits:
            _, _, marker = min(hits)
            return lineno, marker
    return None


def raw_ai_marker(text: str) -> str | None:
    """文头窗口内的**裸子串** AI 字样（归一化匹配，不做边界检查）—— 只用作
    C3/C4 的「未消化信号」，不作 C2 判据。边界规则拒掉的命中（如 `Generated
    by AI on March`）说明这行有 AI 自述嫌疑但引擎不敢确定；这样的文件若又
    没有实质正文，判「空骨架建议删」就是把嫌疑当垃圾扔（round-4 BLOCKER-1）。
    返回原表原文（uncertain_reason 展示用）。
    ⛔ 走 `_norm_guard_line`（比 C2 判据多剥零宽）—— 护栏宽、判据不动。"""
    for _, ln in head_window(text):
        for norm in _guard_variants(ln):
            for nm, orig in zip(_AI_MARKERS_NORM, AI_MARKERS):
                if nm in norm:
                    return orig
    return None


def round_of(name: str) -> str | None:
    m = _ROUND_RE.search(name)
    return m.group(1) if m else None


def round_type(name: str) -> str | None:
    for pat, typ in ROUND_SUBPATTERNS:
        if pat in name:
            return typ
    return None


# ───────────────────────────── 扫描 ─────────────────────────────


def read_text_or_none(p: Path) -> str | None:
    try:
        return p.read_bytes().decode("utf-8")
    except (OSError, UnicodeDecodeError):
        return None


def scan_corpus(
    vault: Path, excluded_roots: list[str]
) -> tuple[dict[str, list[str]], list[tuple[str, str]], dict]:
    """库内 .md 语料：→ (归一化正文 → [相对路径…], [(路径, 正文)…], 统计)。

    排除：一切隐藏目录、`outputs/`、收件箱子树、产物目录子树。
    ⛔ **空正文不进重复索引** —— 否则库内任意两个空骨架互为「正本」，会撑出一条
    有后果的建议删，其证据是「两个都是空的」。C3 虽然先命中，但索引本身必须先干净：
    门要防的是未来次序调整时的静默失效，不只是当下这一次。
    """
    by_body: dict[str, list[str]] = {}
    bodies: list[tuple[str, str]] = []
    stats = {
        "files_scanned": 0,
        "files_indexed": 0,
        "skipped_empty_body": 0,
        "skipped_symlink": 0,
        "skipped_unreadable": 0,
        "truncated": False,
        "file_cap": CORPUS_FILE_CAP,
    }
    for dirpath, dirnames, filenames in os.walk(vault):
        dirnames[:] = sorted(
            d
            for d in dirnames
            if not d.startswith(".")
            and d not in CORPUS_EXCLUDED_DIR_NAMES
            and os.path.realpath(os.path.join(dirpath, d)) not in excluded_roots
        )
        for fn in sorted(filenames):
            if not fn.endswith(".md"):
                continue
            if stats["files_scanned"] >= CORPUS_FILE_CAP:
                # ⛔ 不在此处 return —— 早退会绕过下面的排序尾巴, 让"截断"与"未截断"
                # 两条路径产出形态不同的索引。置位后跳出全部循环, 走同一个出口。
                stats["truncated"] = True
                dirnames.clear()
                break
            p = Path(dirpath) / fn
            stats["files_scanned"] += 1
            if p.is_symlink():
                stats["skipped_symlink"] += 1
                continue
            text = read_text_or_none(p)
            if text is None:
                stats["skipped_unreadable"] += 1
                continue
            if not has_substantive_content(text):
                stats["skipped_empty_body"] += 1
                continue
            body = dup_body(text)
            if not body:
                stats["skipped_empty_body"] += 1
                continue
            rel = p.relative_to(vault).as_posix()
            by_body.setdefault(body, []).append(rel)
            bodies.append((rel, body))
            stats["files_indexed"] += 1
        if stats["truncated"]:
            break
    for v in by_body.values():
        v.sort()
    bodies.sort()
    return by_body, bodies, stats


def near_duplicates(
    body: str, corpus_bodies: list[tuple[str, str]], scan: dict
) -> list[dict]:
    """difflib 近似（按行比对）。⛔ 只标疑似，永不裁决 —— 见显式偏差 1。"""
    if not body:
        return []
    a_lines = body.split("\n")
    la = len(body)
    hits: list[tuple[float, str]] = []
    for rel, other in corpus_bodies:
        if other == body:
            continue  # 逐字相等归 C4，不重复计入疑似
        lb = len(other)
        if la > NEAR_DUP_BODY_CHAR_CAP or lb > NEAR_DUP_BODY_CHAR_CAP:
            scan["skipped_oversize"] += 1
            continue
        if not (1 / NEAR_DUP_LEN_RATIO <= (lb / la if la else 0) <= NEAR_DUP_LEN_RATIO):
            scan["skipped_length_prefilter"] += 1
            continue
        scan["compared_pairs"] += 1
        sm = difflib.SequenceMatcher(None, a_lines, other.split("\n"), autojunk=False)
        if sm.real_quick_ratio() < NEAR_DUP_RATIO or sm.quick_ratio() < NEAR_DUP_RATIO:
            continue
        r = sm.ratio()
        if r >= NEAR_DUP_RATIO:
            hits.append((r, rel))
    hits.sort(key=lambda x: (-x[0], x[1]))
    return [{"path": rel, "ratio": round(r, 4)} for r, rel in hits[:NEAR_DUP_TOP_N]]


# ───────────────────────── 逐份提名（判据次序即本函数结构） ─────────────────────────


def nominate(
    item: dict,
    text: str | None,
    dup_index: dict[str, list[str]],
    corpus_bodies: list[tuple[str, str]],
    scan: dict,
    batch_body_counts: dict[str, int],
) -> dict:
    """对一件材料出提名。**次序即 CRITERIA_ORDER**，先命中者定 verdict；
    后续判据的证据仍全量附上（conflicts / exact_duplicate_of / near_duplicates）。"""
    name = item["name"]
    conflicts: list[dict] = []

    if text is None:
        # 非 UTF-8（PDF/图片等）：除 0 字节外无任何可机械判读的信号 → 不猜。
        if item["size_bytes"] == 0:
            return _fill(
                item,
                "C3_empty_or_skeleton",
                V_DELETE,
                None,
                None,
                "0 字节空文件",
                True,
                conflicts=conflicts,
            )
        return _fill(
            item,
            "C6_undecided",
            V_UNSURE,
            None,
            None,
            "非 UTF-8 文本，本引擎不解析其正文",
            False,
            uncertain_reason="非 UTF-8 文本（如 PDF / 图片），六判据中除「0 字节」外无一可施加",
            ask=UNDECIDED_ASK,
            conflicts=conflicts,
        )

    fm_lines = split_frontmatter(text)[0]
    fm = frontmatter_map(fm_lines)
    # ⛔ 护栏一律扫**不折叠**的全量键值对（round-2 审查 BLOCKER：重复键遮蔽）。
    fm_pairs = frontmatter_pairs(fm_lines)
    typed_rows, unclosed_comment, stripped_comments = _classify_lines_typed(text)
    del typed_rows
    substantive = has_substantive_content(text)
    body = dup_body(text) if substantive else ""
    rnd = round_of(name)
    # C3 护栏信号（显式偏差 15）：frontmatter 里「看着像键但不被键正则认」的行。
    unparsed_fm = [
        ln.strip()
        for ln in fm_lines
        if ln.strip() and not ln.strip().startswith("#") and not _FM_KEY_RE.match(ln)
    ]
    # ⛔ 第五轮终审 HIGH：frontmatter 里的 YAML 注释行（`# source: https://…`）
    # 被上面的 `startswith("#")` 当注释跳过，既不进 unparsed_fm 也不进 map ——
    # 唯一来源写在那儿的文件照样被判空骨架确定删除。与信号⑩同源（引擎剥掉了
    # 内容就该说出来），故并入同一条信号，不新开一条。
    # ⛔ 第六轮终审 HIGH（R6-H1）：**行尾** YAML 注释同样被剥掉且没人收 ——
    # `title: "" # source: https://…` 的唯一来源静默消失，C3/C4 双出口全穿。
    # 与整行注释、跨行 HTML 注释是同一件事：**引擎剥掉了内容就该说出来**。
    # 剥注释的口径与 `_clean_fm_value` 逐字同源（`\s+#` —— 要求 `#` 前有空白，
    # 免得把值里的 `#` 当注释），两处不同判就会又出现一个「看写法决定保护」的缝。
    fm_comment_lines = [
        ln.strip() for ln in fm_lines if ln.strip().startswith("#") and ln.strip("# \t")
    ] + [
        m.group(1).strip()
        for ln in fm_lines
        if not ln.strip().startswith("#")
        and (m := re.search(r"\s+#\s*(.+?)\s*$", ln))
        and m.group(1).strip()
    ]
    # 未消化信号之四：边界规则拒掉的 AI 自述嫌疑（裸子串在场即算，见 raw_ai_marker）。
    ai_suspect = raw_ai_marker(text)
    # 未消化信号之六（round-6 BLOCKER-1）：独立词「AI」结构性信号 —— 不依赖
    # 枚举表，frontmatter 值或文头任一行含独立词 AI 即算嫌疑。
    ai_word_hit = next(
        (
            v
            for v in [*(v for _, v in fm_pairs), *[ln for _, ln in head_window(text)]]
            if _AI_WORD_RE.search(v)
        ),
        None,
    )
    # 未消化信号之七（round-8 BLOCKER-2）：生成断言结构「由 X 生成」/
    # 「generated by X」—— 不枚举模型名，见 `_GEN_CLAIM_CN_RE` 头注。
    gen_claim = find_generation_claim(text)
    # 未消化信号之八（round-8 BLOCKER-2 的另一半）：生成器声明键名本身。
    generator_pairs = [
        (k, v) for k, v in fm_pairs if _norm_fm_key(k) in _GENERATOR_DECL_KEYS
    ]

    # ── 后置证据（不参与次序，但必须全量呈现） ──
    exact_all = sorted(dup_index.get(body, [])) if body else []
    exact_of = exact_all[0] if exact_all else None
    exact_others = exact_all[1:]
    near = near_duplicates(body, corpus_bodies, scan)
    within_batch = bool(body) and batch_body_counts.get(body, 0) > 1
    if within_batch:
        conflicts.append(
            {
                "kind": "duplicate_within_batch",
                "detail": "本批内另有正文逐字相同的材料 —— 谁是正本在只读侧不可判，"
                "故不产出建议删，请你指定保留哪一份",
            }
        )

    def finish(criterion, verdict, ntype, target, basis, confident, **kw):
        if exact_of and criterion != "C4_exact_duplicate":
            conflicts.append(
                {
                    "kind": "exact_duplicate_under_other_verdict",
                    "detail": f"正文与 {exact_of} 逐字相同，但按判据次序本件归 {criterion}"
                    "（次序不因重复而改变，证据在此留痕）",
                }
            )
        if near and criterion != "C6_undecided":
            conflicts.append(
                {
                    "kind": "near_duplicate_suspected",
                    "detail": "疑似与 "
                    + "、".join(f"{n['path']}(ratio {n['ratio']})" for n in near)
                    + " 高相似 —— 疑似不改提名、更不建议删，需你一句话确认",
                }
            )
        return _fill(
            item,
            criterion,
            verdict,
            ntype,
            target,
            basis,
            confident,
            exact_of=exact_of,
            exact_others=exact_others,
            near=near,
            conflicts=conflicts,
            **kw,
        )

    # ── C1 source URL ──
    src = fm.get("source", "")
    if src and _is_primary_source_url(src):
        return finish(
            "C1_source_url",
            V_STAY,
            "primary-record",
            None,
            f"frontmatter source 为一手 URL：{src}",
            True,
        )

    # ── C2 AI 自述 ──
    hit = find_ai_marker(text)
    if hit:
        lineno, marker = hit
        target = f"R{rnd}/" if rnd else DR_TARGET
        return finish(
            "C2_ai_self_declared",
            V_ARCHIVE,
            "secondary-synthesis",
            target,
            f"文头第 {lineno} 行自述「{marker}」"
            + (f"；文件名带 R{rnd}_ 故归轮次目录" if rnd else ""),
            True,
        )

    def _looks_like_source_value(v: str) -> bool:
        """来源声明判定（⛔ substring 级，不要求可机判合法）：值内**任意位置**
        含 `http://` 或 `https://` 即算 —— 前缀判定曾连环穿透：损坏 URL
        （`https://:443/x`，round-5）、autolink 角括号（`<https://…>`，round-6）、
        YAML 标签（`!!str https://…`）与引号包 Markdown 链接（`"[来源](https://…)"`
        —— round-7 BLOCKER-3）。大小写不敏感。"""
        t = v.casefold()
        return "http://" in t or "https://" in t

    # 信号③b：非 source 键名但值是 URL 形态（url:/URL:/Source: 等剪藏工具
    # 常见键名 —— round-5 自审 F2 实证它们曾穿透全部信号被建议删且 URL 零留痕；
    # 值损坏的别名见 `_looks_like_source_value`）。
    # 合法 source 键在此不可能出现（C1 已先行返回）。⚠️ C1 仍只认字面 source 键
    # （R8 稿约定）；本信号只把这类来源摆上台面降 C6，不扩大 C1。
    url_bearing_pairs = [
        (k, v) for k, v in fm_pairs if v and _looks_like_source_value(v)
    ]
    # 信号③a'（round-8 HIGH）：`source` 键名的**大小写/连字符变体**。原实现只查
    # 字面小写 `source`，于是 `Source: DOI:10.1000/xyz` 的唯一来源标识被当作
    # 不存在并 confident 删除。⚠️ 归一只作用于护栏，C1 不动（见 `_norm_fm_key`）。
    source_alias_pairs = [
        (k, v) for k, v in fm_pairs if _norm_fm_key(k) in _SOURCE_DECL_KEYS
    ]
    # 信号③c（round-8 HIGH）：值是 DOI 形态的来源标识（`identifier:` 之类
    # 不在别名表的键名靠它接住）。DOI 不是 URL —— 文案分列，不冒充。
    doi_bearing_pairs = [
        (k, v)
        for k, v in fm_pairs
        if _looks_like_doi_value(v) or _looks_like_isbn_value(v)
    ]
    slept_pairs = [(k, v) for k, v in fm_pairs if _norm_fm_key(k) == "slept_at"]
    # 兜底信号⑨（round-2 方向反转 → round-3 取消白名单，见上方常量段的两轮记录）：
    # frontmatter 里**任何非空值**都算引擎没消化的独有信息。`citation: ISBN …`、
    # `title: <这份材料唯一写下来的那句话>`、长模型名、`Generated by:` 与零宽变体
    # 全部由它兜住 —— 具体信号只负责给出更好的理由，安全底线在这一条。
    # ⛔ 第八轮 HIGH：⑨ 只看**值**，于是把信息写进**键名**（`ISBN_978-…:` 空值）
    # 的形态整条穿透。信息在键名还是在值里，对「引擎没消费它」这件事毫无区别。
    # 判据：键名不在引擎已知集合里（不是它消费过的那些）且看着像编号/标识 ——
    # 直接判「键名非引擎已知」最简单也最不容易再漏。
    _KNOWN_FM_KEYS = frozenset(
        {
            "title",
            "tags",
            "tag",
            "aliases",
            "alias",
            "created",
            "updated",
            "modified",
            "date",
            "cssclass",
            "cssclasses",
            "publish",
            "draft",
            "source",
            "sources",
            "url",
            "doi",
            "slept_at",
            "generator",
            "model",
            "llm",
            "ai",
        }
    )
    unknown_value_pairs = [(k, v) for k, v in fm_pairs if v] + [
        (k, "（值为空，信息在键名里）")
        for k, v in fm_pairs
        if not v and _norm_fm_key(k) not in _KNOWN_FM_KEYS
    ]
    # 未消化信号⑩（round-3 审查 HIGH）：被**闭合** HTML 注释剥掉的原文行。
    # ⚠️ 与①（未闭合注释）对称：①保护的是「不知道被吞了什么」，⑩保护的是
    # 「知道被吞了什么，但引擎没消费它」。此前只有①有保护，于是把唯一来源
    # 写在闭合注释里的文件 C3/C4 双出口全穿。只收**注释里有非空内容**的行。
    commented_out = [ln for ln in stripped_comments if ln.strip()] + fm_comment_lines
    # ⛔ 第九轮 HIGH（R9-H2）：文件名进了 item，但护栏一条都不看它 —— 于是
    # `ISBN_978-7-111-54742-6.md`、`DOI_10.1000_xyz.md` 这类**唯一来源写在文件名
    # 里**的材料，正文一撞上库内某份就被确定删除，文件名里的标识零留痕。
    # 判据与既有来源信号同源（URL / DOI 形态），只是扫描面加上文件名。
    # ⚠️ 用模块级判据，不用 judge() 内那个同名闭包 —— 它定义在本行之后。
    # 文件名里的分隔符常被换成 `_`（`DOI_10.1000_xyz.md`、
    # `source_https_example.test_article.md`），故把 `_` 还原成 `:` 与 `/` 各试一遍。
    _stem = name[:-3] if name.endswith(".md") else name
    name_signal = next(
        (
            _stem
            for probe in (
                _stem,
                _stem.replace("_", ":"),
                _stem.replace("_", "/"),
                _stem.replace("_", ":", 1).replace("_", "/"),
                # ⛔ 第十轮 HIGH（R10-H2）：文件名里一个 `_` 常代表整个 `://`
                # （`source_https_example.test_article.md`）。上面几种还原都还不出
                # `https://`，故显式补一条 scheme 还原。
                # ⚠️ 不能写 `\b(https?)` —— `_` 是词字符，`source_https` 里
                # `https` 前后都没有词边界，那条正则一次也匹配不上（实测）。
                re.sub(r"(?i)(?<![a-z])(https?)[_:]+[/]*", r"\1://", _stem),
                # ⛔ 第十一轮 HIGH（R11-H4）：percent-encoded 的文件名
                # （`source_https%3A%2F%2Fexample.test_article.md`）此前全穿。
                # ⚠️ 用 unquote 而不是再加一条替换规则 —— percent 编码是**有标准**
                # 的，标准解码比枚举替换可靠，这是本卡「开放集合不能枚举、
                # 有结构的可以正面解」的又一次应用。
                unquote(_stem),
                unquote(_stem).replace("_", ":", 1),
            )
            # ⛔ 第十轮 HIGH（R10-H2）：此前用**锚定**的 `_URL_RE.match`，于是
            # `source_https_example.test_article.md` 这类带前缀的文件名，四个
            # probe 都不以 http 开头，整条穿透。文件名是自由拼出来的，判定必须
            # 是 substring 级 —— 与 `_looks_like_source_value` 同口径。
            if (
                "http://" in probe.casefold()
                or "https://" in probe.casefold()
                or _looks_like_doi_value(probe)
                or _looks_like_isbn_value(probe)
            )
        ),
        None,
    )

    def undigested_reason() -> str | None:
        """⛔ 「未消化信号」统一护栏（显式偏差 15）：C3/C4 是仅有的两个产出
        「建议删」的判据，命中时若文件带有引擎未能完全消化的结构信号 ——
        未闭合注释 / 解析不成的 frontmatter 行 / 来源声明（source 键或任意
        URL 形态键值）/ 睡眠台账键 / AI 自述嫌疑 —— 一律降 C6 拿不准。
        判据收窄漏掉的文件曾掉进这两个判据被建议删（round-3 自审 H1-1/H3-1 +
        round-4 BLOCKER-1/BLOCKER-2 + round-5 自审 F2/F3 实证）；
        「安全」是路径属性：必须拦在两个出口，而不是只拦 C3。"""
        if unclosed_comment:
            return "文件以未闭合的 HTML 注释结尾（`<!--` 没等到 `-->`），哪些内容被吞掉引擎猜不了"
        if unparsed_fm:
            return (
                f"frontmatter 含本引擎无法解析为键的行（如 {unparsed_fm[0]!r}），"
                "解析不完整"
            )
        if source_alias_pairs:
            k, v = source_alias_pairs[0]
            return (
                f"frontmatter 声明了 {k}（{v!r}）但不是可机判的"
                "一手 URL —— 来源声明还在，不能当它不存在"
            )
        # ⚠️ URL 在 DOI 之前（自审 S1）：`url: https://doi.org/10.1000/xyz` 两条都
        # 命中，但它**是个网址**（DOI 解析链接）；报成「DOI 来源标识」并附上
        # 「引擎不解引用 DOI」的免责就不准确。更具体的判定先说话。
        if url_bearing_pairs:
            k, v = url_bearing_pairs[0]
            return (
                f"frontmatter 的 {k} 键声明了一个来源 URL"
                f"（{v!r}）—— 来源声明还在，不能当它不存在"
            )
        if doi_bearing_pairs:
            k, v = doi_bearing_pairs[0]
            return (
                f"frontmatter 的 {k} 键声明了一个 DOI 来源标识"
                f"（{v!r}）—— 这是该材料唯一的出处线索，不能当它不存在"
                "（⚠️ 引擎不解析、不解引用 DOI，故只降拿不准，不判一手来源）"
            )
        if slept_pairs:
            return (
                f"frontmatter 带睡眠台账键 slept_at（{slept_pairs[0][1]!r}）—— "
                "它记录着这份材料的起睡时间（引擎在 Sleeping 台账里认识这个键），"
                "删除会把台账状态一起抹掉"
            )
        if ai_suspect:
            return (
                f"文头有疑似 AI 生成自述（「{ai_suspect}」）但按边界规则不构成"
                "确定命中 —— 是自述还是话题提及，引擎拿不准"
            )
        if ai_word_hit:
            return (
                f"文头或 frontmatter 出现独立词「AI」（如 {ai_word_hit!r}），"
                "可能与 AI 生成有关 —— 引擎不解读语义，宁可拿不准"
            )
        if gen_claim:
            return (
                f"文头出现生成断言结构（归一化后片段：{gen_claim!r}）—— 由谁生成"
                "引擎不解读（模型名是开放集合，枚举追不上），但「这是生成物」"
                "这句声明还在，不能当它不存在"
            )
        if generator_pairs:
            k, v = generator_pairs[0]
            return (
                f"frontmatter 带 {k} 键（{v!r}）—— 这类键名**常**用于标注材料的"
                "生成来源（`generator: gpt-4` 之类）。⚠️ 引擎不判断它在这份材料里"
                "到底是不是这个意思（`model: 线性回归` 这样的学习笔记同样会命中），"
                "所以不下结论、只降拿不准"
            )
        if name_signal:
            return (
                f"文件名本身像一条来源标识（{name_signal!r}）—— 引擎没有消费过"
                "文件名里的信息，删掉这份材料，那个标识就没有别的地方留着了"
            )
        if commented_out:
            return (
                f"文件里有被 HTML 注释包起来的内容（如 {commented_out[0].strip()!r}），"
                "引擎把注释整段剥掉了、没有消费它 —— 注释里可能写着这份材料的"
                "来源或说明，删掉就一起没了"
            )
        # ⛔ 兜底（必须排最后：前面每条都能说出更具体的理由）。
        if unknown_value_pairs:
            k, v = unknown_value_pairs[0]
            return (
                f"frontmatter 的 {k} 键有非空值（{v!r}），而引擎没有消费过它的"
                "内容 —— 那可能是这份材料仅存的信息（标题、出处、编号、批注…），"
                "删掉就没了。⚠️ 引擎不判断这个值重不重要：它分不出 `title: t` 与"
                "`title: <你唯一写下的那句话>` 的区别，分不出就不替你决定"
            )
        return None

    # ── C3 空 / 空骨架（⛔ 未消化信号护栏，见显式偏差 15）──
    if not substantive:
        signal = undigested_reason()
        if signal:
            return finish(
                "C6_undecided",
                V_UNSURE,
                None,
                None,
                "无机械判据可施加",
                False,
                uncertain_reason=(
                    f"{signal}，文件又没有实质正文 —— 是空骨架还是「信号还没被"
                    "读懂的文件」拿不准，不敢建议删"
                ),
                ask=UNDECIDED_ASK,
            )
        return finish(
            "C3_empty_or_skeleton",
            V_DELETE,
            None,
            None,
            skeleton_note(text, item["size_bytes"]),
            True,
        )

    # ── C4 精确重复（**逐字相等**才算；近似永不到这里） ──
    # ⛔ 批内也有同稿时**不再**否决 C4（Codex MEDIUM 实证）：只要库内已经有一份
    # 逐字相同的，收件箱这份就是多余的 —— 与批内还有几份同稿无关。
    # ⛔ 未消化信号护栏同样拦 C4（round-4 BLOCKER-2）：C4 只证明「剥掉
    # frontmatter 后正文相等」，不证明「整个文件多余」——带 source 声明等
    # 信号的文件被建议删时信号必须先摆到台面上，删不删由人定。
    if exact_of:
        signal = undigested_reason()
        if signal:
            return finish(
                "C6_undecided",
                V_UNSURE,
                None,
                None,
                "无机械判据可施加",
                False,
                uncertain_reason=(
                    f"{signal}；且正文与 {exact_of} 逐字相同 —— 但「整个文件"
                    "多余」只有正文证据支撑，上述信号未消化，删不删由你定"
                ),
                ask=UNDECIDED_ASK,
            )
        if fm:
            # ⛔ round-5 自审：C4 的正文证据不覆盖 frontmatter 元数据（tags/created
            # 等引擎不消费的键）。不降级（重复多余性成立），但元数据存在必须留痕
            # —— 删除是不可逆执行，痕迹是人的最后一道核对面。
            conflicts.append(
                {
                    "kind": "frontmatter_metadata_present",
                    "detail": "本件 frontmatter 还带有元数据键（"
                    + "、".join(sorted(fm))
                    + "），正文重复证据不覆盖它们 —— 执行删除前请过目",
                }
            )
        if exact_others:
            basis = (
                f"库内已有 {len(exact_all)} 份正文逐字相同的文件："
                + "、".join(exact_all)
                + "。⛔ 哪一份算「正本」不可判（无机械依据），"
                "但收件箱这份相对它们是多余的，故仍建议删"
            )
            conflicts.append(
                {
                    "kind": "multiple_canonical_candidates",
                    "detail": f"库内有 {len(exact_all)} 份同正文文件，"
                    f"`exact_duplicate_of` 取相对路径字典序最小者仅为**可预测的代表**，"
                    "不主张它比其余几份更正本",
                }
            )
        else:
            basis = f"归一化正文与 {exact_of} 逐字相等（sha256 相同）"
        return finish("C4_exact_duplicate", V_DELETE, None, None, basis, True)

    # ── C5 R{n}_ 文件名 ──
    if rnd:
        typ = round_type(name)
        return finish(
            "C5_round_filename",
            V_ARCHIVE,
            typ,
            f"R{rnd}/",
            f"文件名带 R{rnd}_ → 归轮次目录"
            + (
                f"；子模式命中 → 类型 {typ}"
                if typ
                else "；子模式未命中 → 类型留空（去向确定，类型拿不准，不硬填）"
            ),
            True,
            type_uncertain=typ is None,
        )

    # ── C6 兜底：拿不准（不给去向、不给类型） ──
    if within_batch:
        reason = "本批内有正文逐字相同的另一件，谁是正本不可判 —— 不硬猜"
    elif near:
        reason = (
            "疑似与 "
            + "、".join(f"{n['path']}(ratio {n['ratio']})" for n in near)
            + " 高相似，但**未逐字相等** —— 近似不等于重复，不硬猜"
        )
    else:
        reason = (
            "六判据全不命中：无 source URL、文头无可确定的 AI 自述、有实质正文、"
            "与库内无逐字相同正本、文件名无 R{n}_ 轮次标记"
        )
    if ai_suspect:
        # 嫌疑提示对 within_batch / near / 全不命中三个分支统一补挂 ——
        # round-5 自审 F6：只挂在 else 曾让「批内重复 + AI 嫌疑」件的理由缺嫌疑面。
        reason += f"；文头有「{ai_suspect}」字样但按边界规则不算确定自述，请你过目定夺"
    return finish(
        "C6_undecided",
        V_UNSURE,
        None,
        None,
        "无机械判据可施加",
        False,
        uncertain_reason=reason,
        ask=UNDECIDED_ASK,
    )


def _fill(
    item: dict,
    criterion: str,
    verdict: str,
    ntype: str | None,
    target: str | None,
    basis: str,
    confident: bool,
    *,
    uncertain_reason: str | None = None,
    ask: str | None = None,
    type_uncertain: bool = False,
    exact_of: str | None = None,
    exact_others: list[str] | None = None,
    near: list[dict] | None = None,
    conflicts: list[dict] | None = None,
) -> dict:
    out = dict(item)
    out.update(
        {
            "criterion": criterion,
            "verdict": verdict,
            "nomination_type": ntype,
            "target_hint": target,
            "basis": basis,
            "confident": confident,
            "type_uncertain": type_uncertain,
            "uncertain_reason": uncertain_reason,
            "ask": ask,
            "exact_duplicate_of": exact_of,
            "exact_duplicate_others": exact_others or [],
            "near_duplicates": near or [],
            "conflicts": conflicts or [],
        }
    )
    return out



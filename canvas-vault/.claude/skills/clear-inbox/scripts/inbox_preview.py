    L.append(
        f"> 近似比对：阈值 {s['ratio_threshold']}，实比 {s['compared_pairs']} 对；"
        f"因体积跳过 {s['skipped_oversize']} 对、因长度差跳过 {s['skipped_length_prefilter']} 对。"
        f"{s['note']}"
    )
    L.append("")


# ───────────────────────────── 时间 ─────────────────────────────


def parse_now(raw: str) -> datetime:
    """--now → aware datetime。裸时间按 Asia/Shanghai 解释（显式偏差 5）。"""
    try:
        dt = datetime.fromisoformat(raw.replace("Z", "+00:00"))
    except ValueError as e:
        raise SystemExit(
            f"✗ --now 不是合法 ISO-8601 时刻: {raw!r}（例: 2026-08-31T00:00:00+08:00）"
        ) from e
    return dt if dt.tzinfo else dt.replace(tzinfo=_TZ_SHANGHAI)


def _epoch_s(dt: datetime) -> float:
    return dt.timestamp()


def days_between(now_s: float, then_s: float) -> int:
    """整日年龄。⛔ 先把秒差取**最近整秒**再整除 86400 —— 见显式偏差 6。
    用的是 Python `round`（ties-to-even，不是"半数远离零"）；此处只用于吸收
    文件系统纳秒往返的亚微秒抖动，恰好落在 .5 的秒差在真实 mtime 上不会出现。"""
    return int(round(now_s - then_s)) // 86400


#: 时刻不可表示时的占位（不是"没有时间"，是"这个 mtime 超出日历可表示范围"）。
UNREPRESENTABLE = "unrepresentable"


def _fmt(sec: float, tz, pattern: str) -> str:
    """⛔ 极值 mtime（如被置成 9999 年末，+8h 后溢出到 10000 年）会让
    `datetime.fromtimestamp` 抛 OverflowError —— 一个畸形 mtime 不该炸掉整份 preview。
    与 `scripts/daily_review_pick.py::_sh_local` 同款诚实降级：返回占位串，
    **不**伪造一个看似正常的时间。"""
    try:
        return datetime.fromtimestamp(sec, tz=tz).strftime(pattern)
    except (OverflowError, OSError, ValueError):
        return UNREPRESENTABLE


def fmt_utc(sec: float) -> str:
    return _fmt(sec, timezone.utc, "%Y-%m-%dT%H:%M:%SZ")


def fmt_local(sec: float) -> str:
    return _fmt(sec, _TZ_SHANGHAI, "%Y-%m-%d %H:%M")


# ───────────────────────── 文本解析（确定性） ─────────────────────────


def frontmatter_span(lines: list[str]) -> int:
    """frontmatter 块**占用的行数**（含首尾两条分隔线）；无 / 缺闭合时为 0。

    ⛔ 单独抽出来是因为 `head_window` 需要的是「跳过几行」而不是「里面有几个键」。
    早先版本用 `len(fm) + 2` 反推，遇到**空 frontmatter**（`---` 紧接 `---`）时
    `fm == []` 被当成「没有 frontmatter」，报出的行号就整体偏 2 行 —— 依据里的
    行号是给人核对用的，偏了就等于没有。
    """
    if not lines or lines[0].strip() != "---":
        return 0
    end = None
    for i in range(1, len(lines)):
        if lines[i].strip() in ("---", "..."):
            end = i
            break
    if end is None:
        return 0  # 缺闭合 → 视为无 frontmatter
    # ⛔ 还要**真的像** frontmatter（Codex HIGH 实证）：`---\n这是唯一正文\n---`
    # 原先被整段当 frontmatter 吞掉 → 正文为空 → 输出「建议删」。把用户正文误判成
    # 空文件的删除提名，比不提名坏得多。
    for ln in lines[1:end]:
        t = ln.strip()
        if not t or t.startswith("#"):
            continue  # 空行与 YAML 注释不作数
        return end + 1 if _FM_LOOKS_LIKE_KEY_RE.match(ln) else 0
    return end + 1  # 空 frontmatter（`---` 紧接 `---`）


def split_frontmatter(text: str) -> tuple[list[str], list[str]]:
    """→ (frontmatter 行, 其余行)。只认文件头的 `---` 对；缺闭合视为无 frontmatter。"""
    lines = md_splitlines(text)
    n = frontmatter_span(lines)
    return (lines[1 : n - 1] if n else []), lines[n:]


def _clean_fm_value(raw: str) -> str:
    """frontmatter 值清洗：剥行尾 YAML 注释 → 剥成对引号。

    ⛔ 两步缺一不可，且顺序不能反：`source: "https://x" # 官方来源` 若先判引号，
    会因末字符是「源」而走错分支，值带着引号被 URL 判据拒掉，一手来源丢失
    （round-3 自审 H1-6）。
    """
    val = (raw or "").strip()
    val = re.sub(r"\s+#.*$", "", val).strip()
    if len(val) >= 2 and val[0] == val[-1] and val[0] in "\"'":
        val = val[1:-1]
    return val


def frontmatter_pairs(fm_lines: list[str]) -> list[tuple[str, str]]:
    """全部 `key: value` 对，**按出现顺序、不折叠重名键**。

    ⛔ round-2 审查 BLOCKER 的修法：`frontmatter_map` 用 `setdefault` 只留首值，
    于是

        ---
        doi:
        doi: 10.1000/hidden
        ---

    折叠后只剩一个**空**值，所有基于 `fm.items()` 的护栏信号全都扫不到那个 DOI，
    文件被判空骨架确定删除（同形 `url:` 反例同时穿透 C3 与 C4 两个出口）。
    护栏必须看**全部**写下来的行 —— 引擎丢弃了的信息，正是「未消化」的定义。
    ⚠️ 判据侧（C1 取 `fm["source"]`）仍走 `frontmatter_map` 的首值语义，不动：
    改判据取值是有后果的行为变更，不能作为一次护栏加宽的副作用。
    """
    out: list[tuple[str, str]] = []
    for ln in fm_lines:
        m = _FM_KEY_RE.match(ln)
        if m:
            out.append((m.group(1), _clean_fm_value(m.group(2) or "")))
    return out


def frontmatter_map(fm_lines: list[str]) -> dict:
    """顶层 `key: value` 扫描（不引 YAML 依赖；嵌套/列表值不解析，本卡不需要）。
    ⚠️ 重名键取**首值**（既有语义，判据侧依赖它）；护栏侧要看全量请用
    `frontmatter_pairs`。"""
    out: dict[str, str] = {}
    for k, v in frontmatter_pairs(fm_lines):
        out.setdefault(k, v)
    return out


#: ⛔ 第十一轮 HIGH（R11-H1）：`str.splitlines()` 把 U+001C-1E/U+0085/U+2028/
#: U+2029 也当行界，于是围栏内的 U+001D 被改写成换行，`a<U+001D>b` 与 `a\nb`
#: 的 dup_body 相等 → 确定删除。Markdown 的行界只有 \n / \r\n / \r。
#: ⚠️ 这是「按 Markdown 规范判结构却用了 Unicode 语义」的**第三处**，
#: 与开篇 NBSP、第十轮三条同源。分行是最底层的一步，漏了它上面全白做。
_MD_LINE_SPLIT_RE = re.compile(r"\r\n|\r|\n")


def md_splitlines(text: str) -> list[str]:
    """按 **Markdown 行界**分行（只认 \n / \r\n / \r），不用 `str.splitlines()`。"""
    parts = _MD_LINE_SPLIT_RE.split(text)
    if parts and parts[-1] == "":
        parts.pop()  # 末尾换行不产生空行，与 splitlines 语义一致
    return parts


def _classify_lines_typed(text: str) -> tuple[list[tuple[str, str]], bool, list[str]]:
    """→ [((行, 种类), …), 是否结束于未闭合的 HTML 注释, 被注释剥掉过的原文行]。

    种类三态：`"fence"`（围栏分隔行）/ `"code"`（围栏内容）/ `"text"`。
    三态化是因为二态布尔回答不了「围栏**内容**里长得像围栏的行」——
    Markdown 围栏语法速查（```` 里嵌 ``` 与 ~~~）曾被 `has_substantive_content`
    用 `_FENCE_RE` 整体剔除 → 判成空骨架 → 建议删（round-3 自审 B3-3）。
    分隔行由状态机精确标记，内容行一律是内容。

    第二返回值供 C3 护栏（显式偏差 15）使用：`<!--` 没等到 `-->` 就到了 EOF
    时，哪些内容被注释吞掉是引擎猜不了的 —— 这种文件不许被判「空骨架」。

    ⛔ 围栏状态机是 Codex 两条 BLOCKER 的正解。原先没有它：
      - `~~~` 被当成"纯结构行"删掉，围栏里的 `# comment` 又被当成 Markdown 标题删掉，
        于是一份只有一段 shell 代码的文件被判成空骨架 → **建议删**；
      - 而文件头明明声明着"代码块内容留在正文里"。声明与实现对不上就是掩饰。
    注释剥离只作用于围栏外：代码里的 `<!-- -->` 是代码，不是说明。
    """
    _, rest = split_frontmatter(text)
    rows: list[tuple[str, str]] = []
    stripped_comments: list[str] = []
    # ⛔ 第十一轮 HIGH（R11-H2）：分类器此前只有 fence/comment 状态，没有
    # **raw HTML block**。于是 `<pre>` 里的 `# source: https://…` 被当成 ATX
    # 标题丢弃，正文一撞库就确定删除、来源零留痕。CommonMark §4.6 的 HTML block
    # 里没有 Markdown 结构，那些行是字面内容。
    in_html = False
    in_fence = False
    fence_char = ""
    fence_len = 0
    in_comment = False
    for ln in rest:
        m = _FENCE_RE.match(ln)
        if m and not in_comment:
            tok = m.group(1)
            # ⛔ CommonMark 4.4：反引号围栏的 info string **不得含反引号** ——
            # ```foo`bar 不是合法开启行（round-6 BLOCKER-3：该行曾被当开启、
            # 下一行被当关闭、正文再被标题剥掉 → 空骨架建议删）。tilde 围栏
            # 的 info string 允许反引号，不受此限。
            if not in_fence and not (tok[0] == "`" and "`" in ln[m.end() :]):
                in_fence, fence_char, fence_len = True, tok[0], len(tok)
                # ⛔ 第七轮终审 HIGH（R7-H1）：围栏开启行的 **info string**
                # （`~~~ {source=https://…}`）整行被标成 "fence" 后不进正文，
                # 写在那儿的来源静默消失。这是「来源被引擎剥掉」的**第四种写法**
                # （前三种：跨行 HTML 注释 / fm 整行 YAML 注释 / fm 行尾注释）。
                info = ln[m.end() :].strip()
                if info:
                    stripped_comments.append(info)
                rows.append((ln, "fence"))
                continue
            # ⛔ 关闭围栏 = 同字符 **且长度 ≥ 开启长度、围栏后仅 ASCII 空白**
            # （CommonMark 4.5）。只比字符曾让 ```` 里的 ``` 被当关闭、``` 后带
            # info string 的行也被当关闭 —— 围栏内容 `# keep` 落到围栏外被剥，
            # 整份文件被误判成空骨架 → 建议删（round-2 B3 实证）。
            # ⛔ 「仅空白」必须逐字符限 ASCII 空格/制表符：`str.strip()` 接受一切
            # Unicode 空白，行尾一个 U+00A0（网页复制常见）曾让该行被当成合法
            # 关闭围栏 → 围栏提前闭合 → 建议删（round-3 Codex BLOCKER；NBSP 行
            # 在 CommonMark 里是围栏内容）。
            if (
                tok[0] == fence_char
                and len(tok) >= fence_len
                and all(c in " \t" for c in ln[m.end() :])
            ):
                in_fence, fence_char, fence_len = False, "", 0
                rows.append((ln, "fence"))
                continue
        if in_fence:
            rows.append((ln, "code"))
            continue
        # HTML block：`<pre|script|style|textarea>` 起、对应闭合标签止
        # （CommonMark §4.6 type 1 —— 最保守的一种，只认这四个标签）。
        if not in_html and re.match(
            r"^ {0,3}<(?:pre|script|style|textarea)(?:[ \t>]|$)", ln, re.IGNORECASE
        ):
            in_html = True
        if in_html:
            rows.append((ln, "code"))  # 与围栏同待遇：字面内容，不套 Markdown 结构
            if re.search(r"</(?:pre|script|style|textarea)>", ln, re.IGNORECASE):
                in_html = False
            continue
        kept, rem = "", ln
        while rem:
            if in_comment:
                i = rem.find("-->")
                if i < 0:
                    # ⛔ 第五轮终审 HIGH：跨行注释里**中间那些整行**此前没被收集
                    # （只收了闭合那一行的 `rem[:i]`），于是
                    #   <!--
                    #   source: https://…
                    #   -->
                    # 的来源整条丢掉，文件被判空骨架确定删除。单行注释反而受保护。
                    stripped_comments.append(rem)
                    break
                # ⛔ round-4 验证 MEDIUM：收集的必须是**注释内部的内容**。
                # 先前记的是「被剥掉的原文片段」，于是 `<!---->` 这种空注释也
                # 触发信号⑩，把安全方向的少删又扩大了一圈。
                stripped_comments.append(rem[:i])
                rem, in_comment = rem[i + 3 :], False
            else:
                i = rem.find("<!--")
                if i < 0:
                    kept += rem
                    break
                kept += rem[:i]
                rem, in_comment = rem[i + 4 :], True
        rows.append((kept, "text"))
        # ⛔ round-3 审查 HIGH：闭合注释被这里整段剥掉，而来源/生成信号只扫
        # frontmatter，⑨ 兜底也只覆盖 frontmatter —— 于是
        # `<!-- source: https://… -->`、`<!-- DOI:10.1000/… -->`、
        # `<!-- citation: ISBN … -->` 这类「唯一信息写在注释里」的文件
        # C3/C4 双出口全穿。只有**未闭合**注释受保护，闭合的反而不受。
        # 注释内容在上面的闭合分支里逐段收集，与「未闭合注释」对称地作信号。
    return rows, in_comment, stripped_comments


def _classify_lines(text: str) -> list[tuple[str, bool]]:
    """二态视图（该行是否属围栏区），供 `dup_body` 等逐字保真路径使用。
    三态细节见 `_classify_lines_typed`。"""
    return [(ln, kind != "text") for ln, kind in _classify_lines_typed(text)[0]]


def dup_body(text: str) -> str:
    """**逐字保真**的正文形态 —— C4「精确重复」的唯一比对依据。

    只做无语义的归一：丢标题行（围栏外）、行尾空白 rstrip、丢空行、NFC。
    ⛔ **不** `.strip()` 每行、**不**剥列表符号：那会抹掉代码缩进，让
    `if ok:` + 缩进 `run()` 与 `if ok:` + 顶格 `run()` 判成"逐字相等"，
    进而对一份语义完全不同的文件给出「建议删」（Codex BLOCKER 实证）。
    有后果的提名，依据必须逐字。
    ⛔ 标题不进比对：同一段材料被粘两份时标题常不同（R8 判据 4 说的是「正文高相似」）。
    """
    parts: list[str] = []
    for ln, is_code in _classify_lines(text):
        if not is_code and _HEADING_RE.match(ln):
            continue
        # ⛔ 第九轮 HIGH（R9-H1）：此前无条件 `rstrip()` + 丢空行，把**有语义的
        # 空白**一起抹了 —— Markdown 行尾双空格是硬换行、空行是段落边界、围栏
        # 里的空格与空行更是字面内容。于是 `alpha  \nbeta` 与 `alpha\nbeta`
        # 被判「逐字相等」并确定删除。⚠️ 判据名叫「精确重复」，比较形态却是
        # 有损投影 —— 名实不符本身就是缺陷。
        if is_code:
            # 围栏内一律逐字保真（含空行与行尾空格）
            parts.append(nfc(ln))
            continue
        # ⛔ 第十轮 HIGH（R10-H1）：`rstrip()` / `strip()` 是 Unicode 语义，
        # 会把 NBSP 等**有语义的**空白也剥掉，两个 U+00A0 还被改写成两个 ASCII
        # 空格 —— 判据仍在做有损投影。行尾空白只按 ASCII space/tab 处理。
        t = ln.rstrip(" \t")
        if not t.strip(" \t"):
            parts.append("")  # 段落边界是语义，不能丢
            continue
        if len(ln) - len(t) >= 2 and not ln[len(t) :].strip(" \t"):
            t += "  "  # 行尾 ≥2 个 ASCII 空格 = 硬换行，保留其语义
        parts.append(nfc(t))
    return "\n".join(parts)


def has_substantive_content(text: str) -> bool:
    """这份材料有没有**实质正文** —— C3「空 / 空骨架」的唯一依据。

    与 `dup_body` 刻意分家：这里回答「是不是只剩脚手架」，可以激进归一化
    （剥列表符、丢纯结构行）；那里回答「是不是逐字相同」，必须逐字保真。
    合用一个函数正是 Codex BLOCKER 的根因。
    ⛔ 用三态视图：围栏**内容**行（哪怕长得像围栏标记，如 Markdown 围栏语法
    速查里的 ``` 行）都算实质正文；只有状态机标记的分隔行不算
    （round-3 自审 B3-3）。
    """
    for ln, kind in _classify_lines_typed(text)[0]:
        if kind == "code":
            if ln.strip():
                return True  # 围栏内容 = 真实材料（含长得像围栏的行）
            continue
        if kind == "fence":
            continue
        if _HEADING_RE.match(ln):
            # ⛔ 用户裁决（2026-09-02）：**标题里写了字就算实质正文**。
            # 起因是量化取样时发现，`# 微积分基本定理的两种证法` 这种「只写了
            # 标题、正文还没动笔」的日常笔记，在旧口径下是 `建议删 +
            # confident=true` —— 那不是对抗构造，是真实使用场景。
            # 论证与本卡「取消 frontmatter 白名单」逐字同构：标题可能是随手一个
            # 字，也可能是这份材料唯一写下来的东西，引擎分不出，分不出就不该
            # 替用户决定。
            # ⛔ **声明收窄（第五轮终审实测证伪）**：本裁决只关闭 **C3 那一半**。
            # C4 侧 `dup_body()` 仍把标题整行丢掉再比对，所以
            # `# 只有这一份写了母本第37页` + 与库内相同的正文，照样是
            # `C4 建议删 + confident=true` —— 标题里的独有信息随重复件一起没了。
            # 我曾在 commit 里写「顺带关闭了 U+3164/U+2800 那条 BLOCKER」，
            # 那句话**过宽**：隐形字符伪装的标题在 C3 侧确实被接住了，
            # 但只要它带着一段与库内重复的正文，C4 侧照样确定删除。
            # 用户第二次裁决（2026-09-02）：**C4 不跟进** —— 让标题进重复比对会
            # 使「同一段正文粘两份、标题不同」不再算重复（5 件取样只剩 1 件被
            # 识别），而那正是清收件箱最常见的场景。保住重复识别，代价如实登记。
            # ⚠️ 代价如实：C3 的可确定删除面明显收窄（10 件取样从 10 → 5）。
            # ⛔ 第八轮 HIGH 收窄措辞：此前写「只剩五种」并逐一列举 —— 那是
            # **数出来的**，实测还有空围栏、空列表、全空值 frontmatter 同样落
            # C3。**数「剩几种」本身就是过宽的写法**：可达面由判据的性质决定，
            # 不由我列举的完整度决定，列举永远会漏。
            # 准确的说法是性质：`has_substantive_content` 找不到任何一个
            # 「剥掉结构记号后还剩字符」的行时，才判空骨架。
            if _atx_heading_text(ln):
                return True
            continue
        t = _LIST_PREFIX_RE.sub("", ln).strip(" \t")
        if t and not _is_structural_line(t):
            return True
    return False


def skeleton_note(text: str, size: int) -> str:
    """空/骨架的**逐项计数**依据 —— 不是「看起来是空的」而是数出来的。

    ⛔ fences 只数围栏**分隔行**（三态视图），围栏内的空行归入句尾的
    「其余皆空行」—— 原先 `sum(... if c)` 把围栏内空行也算进「代码围栏 N 行」，
    与同一句里的「其余皆空行」不构成划分（round-3 自审 B3-5）。
    """
    if size == 0:
        return "0 字节空文件"
    rows = _classify_lines_typed(text)[0]
    headings = sum(1 for ln, k in rows if k == "text" and _HEADING_RE.match(ln))
    struct = sum(
        1 for ln, k in rows if k == "text" and not _HEADING_RE.match(ln) and ln.strip()
    )
    fences = sum(1 for _, k in rows if k == "fence")
    return (
        f"剥离 frontmatter / HTML 注释后实质正文 0 字符"
        f"（{size} 字节文件：标题 {headings} 行、纯结构行 {struct} 行、"
        f"代码围栏 {fences} 行、其余皆空行或注释）"
    )


def head_window(text: str) -> list[tuple[int, str]]:
    """C2 扫描窗口：frontmatter 行 + 其后前 HEAD_SCAN_LINES 行；返回 (1-based 行号, 原文)。"""
    lines = md_splitlines(text)
    n = frontmatter_span(lines)
    win: list[tuple[int, str]] = [(i + 1, lines[i]) for i in range(min(n, len(lines)))]
    for j, ln in enumerate(lines[n : n + HEAD_SCAN_LINES]):
        win.append((n + j + 1, ln))
    return win


def _norm_ai_line(ln: str) -> str:
    """AI 标记匹配前的行归一：连续空白（含 NBSP 等一切 Unicode 空白）折叠为
    单空格 + casefold。⛔ 大小写/空白变体曾穿透字面量表与裸子串护栏的双层 ——
    `generated by ai`（全小写）、`GENERATED BY AI`、内部 NBSP 形态都曾在无正文
    时掉进 C3 建议删（round-5 审查 BLOCKER-1）。归一化是确定性的，二跑逐字节
    相等不受影响；basis 里的标记文本以归一化形态呈现，行号仍准确。"""
    return " ".join(ln.split()).casefold()


#: 不可见字符：**按 Unicode 类别判定，不枚举**。
#: ⛔ round-3 审查 BLOCKER：上一版写成六个码点的有限表
#: （ZWSP/ZWNJ/ZWJ/WORD JOINER/BOM/SOFT HYPHEN），于是 U+2063 INVISIBLE
#: SEPARATOR 以及 U+200E/200F/061C/034F/FE0F/2062/180E/202E 共 9 个同族**全部
#: 穿透**，C3 与 C4 两个出口都中。这与 round-2 的模型名教训是同一件事：
#: **不可见字符不是一张能数完的表**，判它得按类别而不是按名单。
#:   Cf = 格式字符（零宽空格/连接符/双向控制/不可见分隔符…）
#:   Mn = 非间距标记（VS16、CGJ 这类零宽度记号）
#:   Cc = 控制字符
#: ⚠️ 只用在**护栏匹配面**：剥掉组合记号会改变带重音文本的词形，但护栏只判
#: 「这行像不像生成声明」，方向是更容易命中；产物输出一律走原文，不受影响。
#: ⛔ **类别判定同样不完备，如实登记原理上限**（round-4 验证实测）：
#: `U+3164 HANGUL FILLER`（Lo，字母）与 `U+2800 BRAILLE PATTERN BLANK`（So，符号）
#: 在屏幕上是空白，但 Unicode 把它们归为字母/符号，`isspace()` 也是 False ——
#: 机械上它们就是普通字符。把 Lo/So 整类剥掉会连正常韩文与盲文一起剥，那是
#: 更坏的交易。**「视觉上不可见」需要字形宽度数据才判得了，不是字符属性能决定的**，
#: 因此 `# Genera<U+3164>ted by GPT-4` 这类构造仍会落 C3 建议删。
#: 结构化的兜底得改 C3 对**标题行**的处理（现在标题不算实质正文），那是判据面
#: 的语义变更，超出 CARD-G5-6c 范围 —— 登记待裁决，不在本卡内改。
_INVISIBLE_CATEGORIES = frozenset({"Cf", "Mn", "Cc"})


def _strip_invisible(s: str, repl: str) -> str:
    """把不可见字符替换成 `repl`（`" "` 还原词间分隔；`""` 还原词内断裂）。

    ⛔ round-4 验证 BLOCKER 的一半：**删版必须连空白类一起删**。
    `Genera<U+200A>ted`（HAIR SPACE，Zs）此前只被 `_norm_ai_line` 的 `split()`
    折叠成普通空格，词照样是拆开的 —— 删版不删它，两个变体就都还原不出
    `generated`。
    ⚠️ 但删版**保留 ASCII 空格与制表符**：把它们也删掉，`generated by GPT-4`
    在删版里就成了 `generatedbyGPT-4`，骨架永远认不出，删版等于自废。
    要删的是「看不见、又不是正常词间空格」的那一类 —— Cf/Mn/Cc 加上**非 ASCII**
    的空白（Zs/Zl/Zp，如 HAIR SPACE）。两个变体这才真正互补：
      `Genera<U+200A>ted by GPT-4` → 删版还原出 `Generated by GPT-4`；
      `Generated<U+200A>by GPT-4`  → 换空格版还原出 `Generated by GPT-4`。
    """
    return "".join(
        repl
        if (
            unicodedata.category(c) in _INVISIBLE_CATEGORIES
            or (c.isspace() and c not in " \t")
        )
        else c
        for c in s
    )


def _guard_variants(ln: str) -> tuple[str, str]:
    """护栏归一的**两种**零宽还原，都要试。

    ⛔ round-3 审查 BLOCKER：上一版只做「零宽→空格」，那只对**词间**插入成立
    （`by<ZWSP>GPT` → `by GPT`）。零宽插在**词内部**时（`genera<ZWSP>ted`），
    换空格反而把关键词拆成 `genera ted`，骨架与标记表一起失效 —— 比不处理更糟。
    两种还原互补，没有哪一种单独够用：
      · 换空格：还原词间分隔（`by<ZWSP>GPT` → `by gpt`）；
      · 直接删：还原词内断裂（`genera<ZWSP>ted` → `generated`）。
    调用方对两个变体分别匹配，任一命中即算 —— 护栏宁可宽。
    """
    return (
        _norm_ai_line(_strip_invisible(ln, " ")),
        _norm_ai_line(_strip_invisible(ln, "")),
    )


def _norm_guard_line(ln: str) -> str:
    """**护栏专用**归一：先把零宽字符换成空格，再走 `_norm_ai_line`。

    ⛔ 刻意与 C2 判据用的 `_norm_ai_line` 分家，不是图省事：C2 命中意味着
    「AI 自述 · 确定归档 · confident=true」，是**有后果的提名**，扩大它的命中面
    必须是明写的决定；护栏只降 C6，宽一点的代价仅是少几条「建议删」。
    两者混用等于让一次护栏加宽顺带扩大确定提名面。

    ⚠️ **承重面如实声明**（round-2 负控 M-ZEROWIDTH 实测，别高估这一层）：
    回退本函数后套件**一门都不红**，因为 `Generated by<ZWSP>GPT-4` 与
    `本文由<ZWSP>X<ZWSP>生成` 在 `_norm_ai_line` 下**已经**命中骨架 ——
    `_GEN_CLAIM_EN_RE` 的非词字符段会吃掉零宽（Cf 类不算词字符），
    `_GEN_CLAIM_CN_RE` 的非句读字符类同样吃它。一条修法顺手覆盖了另一条。
    本函数真正承重的只有 `raw_ai_marker`：零宽插在标记表项**中间**时
    （`Generated by<ZWSP>AI Lab`、`由<ZWSP>AI<ZWSP>生成`），不剥零宽就匹配不到
    表项，ai_suspect 信号哑火，材料改由靠后的 gen_claim 接住。
    ⚠️ 所以它是一层**理由质量**而非安全底线：两种情况下材料都不会被删，
    差别只在 `uncertain_reason` 说的是「疑似 AI 自述」还是「生成断言结构」。
    留着它是因为前者对人更有用；但不要把它写成安全防线。
    """
    return _norm_ai_line(_strip_invisible(ln, " "))



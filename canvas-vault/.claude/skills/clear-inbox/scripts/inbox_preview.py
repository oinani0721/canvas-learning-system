#: 人话时区：**固定 +08:00**，刻意不走 `ZoneInfo("Asia/Shanghai")`。
#: ⛔ 理由是本卡有「二跑逐字节相等」硬门，而该门必须**跨宿主**成立：ZoneInfo 在装了

def _atx_heading_text(ln: str) -> str:
    """ATX 标题行里**真正的标题文字**（去掉 opening 与可选的 closing 序列）。

    ⛔ 第九轮审查 HIGH（R9-H3）：此前用 `ln.lstrip(" \t#")` 一把撸掉所有井号，
    于是 `# # #` 的**中间那个 `#`**（它是可见的标题内容）被当成 opening 的一部分
    剥掉，整行判成空标题 → 文件被确定删除。ATX 的结构是
    `opening(1-6 个 #) + 空白 + content + 可选 closing(全 # 且前有空白)`，
    分离得按这个结构走，不能靠字符集剥离。
    """
    m = re.match(r"^ {0,3}(#{1,6})(?:[ \t]+|$)", ln)
    if not m:
        return ""
    # ⛔ 第十轮 HIGH（R10-H3）：这里的空白**只能是 ASCII space/tab**。
    # Python 的 `.strip()` 与 `\s` 默认是 Unicode 语义，于是 `# <NBSP>#` 里那个
    # NBSP 被当成 closing 前的分隔符，末尾可见的 `#` 被当收尾序列剥掉 → 空标题
    # → 确定删除。CommonMark §4.2 的 closing 必须由 space/tab 与内容分开。
    # ⚠️ 这与本卡开篇那条 NBSP 是**同一个陷阱**：该用 ASCII 口径的地方用了
    # Unicode 口径。同一个坑在这张卡里踩了两次。
    rest = ln[m.end() :].strip(" \t")
    closing = re.search(r"(?:^|[ \t])(#+)$", rest)
    if closing:
        rest = rest[: closing.start()].strip(" \t")
    return rest


def _is_structural_line(t: str) -> bool:
    """纯结构行判定（分隔线 / 表格分隔 / 空列表符）。"""
    if not _ONLY_STRUCT_RE.match(t):
        return False
    kinds = {c for c in t if c in _STRUCT_CHARS}
    if len(kinds) > 1:
        return False
    core = t.strip(" \t")
    if not core:
        return True
    ch = core[0]
    # 分隔线（CommonMark 要求 ≥3 个）/ 引用与标题记号 / 表格分隔（含 `-`）
    if ch in "-=*_" and len(core) >= 3:
        return True
    if ch == "#":
        # ⛔ 第九轮 HIGH（R9-H3）：ATX 最多六级，`#######`（7 个）**不是**空标题
        # 模板而是普通文本。此前 `set(core) <= {ch}` 把任意个数都当结构。
        return len(core) <= 6
    return ch in ">:|" and set(core) <= {ch} and len(core) >= 3


#: 代码围栏（``` 或 ~~~，允许**最多 3 个空格**缩进 —— ⛔ 必须是字面空格：
#: `\s{0,3}` 会放行制表符，而 CommonMark 里制表符缩进 ≥4 列是缩进代码块，
#: `\t```` 既能开也能**关**围栏，会让围栏提前闭合、其后的标题被剥（round-3 自审 B3-4）。
_FENCE_RE = re.compile(r"^ {0,3}(`{3,}|~{3,})")
#: ⛔ YAML 映射键必须是 `key:` 后接**空白或行尾**：正文行 `http://example.com/path`
#: 里的 `http:` 曾被当成键，整篇被吞成 frontmatter → 空骨架 → 建议删（round-2 H3）。
#: 连带：`source:https://x`（冒号后无空格）此后不再识别为键 —— 若它是块内首个有效
#: 行则整块降为正文，否则被 span 吞掉；两种形态都由 C3 护栏（显式偏差 15）兜住落 C6。
#: 冒号前允许空白（`title : x` 与 `_FM_LOOKS_LIKE_KEY_RE` 同口径，pyyaml 亦认它是键；
#: round-3 自审 H3-3：两条正则曾对「什么算键」各说各话，span 认而 map 不认 → 空正文）。
_FM_KEY_RE = re.compile(r"^([A-Za-z_][A-Za-z0-9_-]*)\s*:(?:\s+(.*))?\s*$")
#: frontmatter 首个有效行必须像 YAML 映射键 —— 否则那只是被两条 `---` 夹住的正文
_FM_LOOKS_LIKE_KEY_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_-]*\s*:(?:\s|$)")
#: URL 形状初筛（`https?://\S+` 会把 `https://?` 也认成一手来源，Codex HIGH）。
#: ⛔ 但正则列不尽 authority 段的空 host 形态（`https://:443/x`、`https://user@/x`
#: 都能过它）——host 非空由 `_is_primary_source_url` 的 urlsplit 检查保证
#: （round-2 H1 实证），本正则只负责拦明显不是 URL 的值。
#: re.I：URI scheme 按 RFC 3986 §3.1 大小写不敏感，`HTTPS://example.com` 也是
#: 一手来源（round-3 自审 H1-2）；大小写归一后 scheme 检查在 `_is_primary_source_url`
#: 里仍保留作防御深度。
_URL_RE = re.compile(r"^https?://[^\s/?#]+\S*$", re.IGNORECASE)


def _is_primary_source_url(src: str) -> bool:
    """C1 的机械判据：`scheme ∈ {http, https}` **且 hostname 非空**才算一手来源。
    解析异常一律不算 URL —— 方向安全（不误判一手，材料落后续判据）。"""
    if not _URL_RE.match(src):
        return False
    try:
        parts = urlsplit(src)
    except ValueError:
        return False
    return parts.scheme in ("http", "https") and bool(parts.hostname)


_ROUND_RE = re.compile(r"(?:^|[^0-9A-Za-z])R(\d{1,4})_")



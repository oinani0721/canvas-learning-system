def parse_now(raw: str) -> datetime:
    """--now → aware datetime。裸时间按 Asia/Shanghai 解释（显式偏差 5）。"""
    try:
        dt = datetime.fromisoformat(raw.replace("Z", "+00:00"))
    except ValueError as e:
        raise SystemExit(
            f"✗ --now 不是合法 ISO-8601 时刻: {raw!r}（例: 2026-08-31T00:00:00+08:00）"
        ) from e
    return dt if dt.tzinfo else dt.replace(tzinfo=_TZ_SHANGHAI)


def _epoch_s(dt: datetime) -> float:
    return dt.timestamp()


def days_between(now_s: float, then_s: float) -> int:
    """整日年龄。⛔ 先把秒差取**最近整秒**再整除 86400 —— 见显式偏差 6。
    用的是 Python `round`（ties-to-even，不是"半数远离零"）；此处只用于吸收
    文件系统纳秒往返的亚微秒抖动，恰好落在 .5 的秒差在真实 mtime 上不会出现。"""
    return int(round(now_s - then_s)) // 86400


#: 时刻不可表示时的占位（不是"没有时间"，是"这个 mtime 超出日历可表示范围"）。
UNREPRESENTABLE = "unrepresentable"


def _fmt(sec: float, tz, pattern: str) -> str:
    """⛔ 极值 mtime（如被置成 9999 年末，+8h 后溢出到 10000 年）会让
    `datetime.fromtimestamp` 抛 OverflowError —— 一个畸形 mtime 不该炸掉整份 preview。
    与 `scripts/daily_review_pick.py::_sh_local` 同款诚实降级：返回占位串，
    **不**伪造一个看似正常的时间。"""
    try:
        return datetime.fromtimestamp(sec, tz=tz).strftime(pattern)
    except (OverflowError, OSError, ValueError):
        return UNREPRESENTABLE


def fmt_utc(sec: float) -> str:
    return _fmt(sec, timezone.utc, "%Y-%m-%dT%H:%M:%SZ")


def fmt_local(sec: float) -> str:
    return _fmt(sec, _TZ_SHANGHAI, "%Y-%m-%d %H:%M")


# ───────────────────────── 文本解析（确定性） ─────────────────────────


def frontmatter_span(lines: list[str]) -> int:
    """frontmatter 块**占用的行数**（含首尾两条分隔线）；无 / 缺闭合时为 0。

    ⛔ 单独抽出来是因为 `head_window` 需要的是「跳过几行」而不是「里面有几个键」。
    早先版本用 `len(fm) + 2` 反推，遇到**空 frontmatter**（`---` 紧接 `---`）时
    `fm == []` 被当成「没有 frontmatter」，报出的行号就整体偏 2 行 —— 依据里的
    行号是给人核对用的，偏了就等于没有。
    """
    if not lines or lines[0].strip() != "---":
        return 0
    end = None
    for i in range(1, len(lines)):
        if lines[i].strip() in ("---", "..."):
            end = i
            break
    if end is None:
        return 0  # 缺闭合 → 视为无 frontmatter
    # ⛔ 还要**真的像** frontmatter（Codex HIGH 实证）：`---\n这是唯一正文\n---`
    # 原先被整段当 frontmatter 吞掉 → 正文为空 → 输出「建议删」。把用户正文误判成
    # 空文件的删除提名，比不提名坏得多。
    for ln in lines[1:end]:
        t = ln.strip()
        if not t or t.startswith("#"):
            continue  # 空行与 YAML 注释不作数
        return end + 1 if _FM_LOOKS_LIKE_KEY_RE.match(ln) else 0
    return end + 1  # 空 frontmatter（`---` 紧接 `---`）


def split_frontmatter(text: str) -> tuple[list[str], list[str]]:
    """→ (frontmatter 行, 其余行)。只认文件头的 `---` 对；缺闭合视为无 frontmatter。"""
    lines = text.splitlines()
    n = frontmatter_span(lines)
    return (lines[1 : n - 1] if n else []), lines[n:]


def frontmatter_map(fm_lines: list[str]) -> dict:
    """顶层 `key: value` 扫描（不引 YAML 依赖；嵌套/列表值不解析，本卡不需要）。"""
    out: dict[str, str] = {}
    for ln in fm_lines:
        m = _FM_KEY_RE.match(ln)
        if not m:
            continue
        val = (m.group(2) or "").strip()
        # 先剥行尾 YAML 注释再剥引号 —— 两步缺一不可，且顺序不能反：
        # `source: "https://x" # 官方来源` 若先判引号会因末字符是「源」而走错分支，
        # 值带着引号被 URL 判据拒掉，一手来源丢失（round-3 自审 H1-6）。
        val = re.sub(r"\s+#.*$", "", val).strip()
        if len(val) >= 2 and val[0] == val[-1] and val[0] in "\"'":
            val = val[1:-1]
        out.setdefault(m.group(1), val)
    return out


def _classify_lines_typed(text: str) -> tuple[list[tuple[str, str]], bool]:
    """→ [((行, 种类), …), 是否结束于未闭合的 HTML 注释]。

    种类三态：`"fence"`（围栏分隔行）/ `"code"`（围栏内容）/ `"text"`。
    三态化是因为二态布尔回答不了「围栏**内容**里长得像围栏的行」——
    Markdown 围栏语法速查（```` 里嵌 ``` 与 ~~~）曾被 `has_substantive_content`
    用 `_FENCE_RE` 整体剔除 → 判成空骨架 → 建议删（round-3 自审 B3-3）。
    分隔行由状态机精确标记，内容行一律是内容。

    第二返回值供 C3 护栏（显式偏差 15）使用：`<!--` 没等到 `-->` 就到了 EOF
    时，哪些内容被注释吞掉是引擎猜不了的 —— 这种文件不许被判「空骨架」。

    ⛔ 围栏状态机是 Codex 两条 BLOCKER 的正解。原先没有它：
      - `~~~` 被当成"纯结构行"删掉，围栏里的 `# comment` 又被当成 Markdown 标题删掉，
        于是一份只有一段 shell 代码的文件被判成空骨架 → **建议删**；
      - 而文件头明明声明着"代码块内容留在正文里"。声明与实现对不上就是掩饰。
    注释剥离只作用于围栏外：代码里的 `<!-- -->` 是代码，不是说明。
    """
    _, rest = split_frontmatter(text)
    rows: list[tuple[str, str]] = []
    in_fence = False
    fence_char = ""
    fence_len = 0
    in_comment = False
    for ln in rest:
        m = _FENCE_RE.match(ln)
        if m and not in_comment:
            tok = m.group(1)
            # ⛔ CommonMark 4.4：反引号围栏的 info string **不得含反引号** ——
            # ```foo`bar 不是合法开启行（round-6 BLOCKER-3：该行曾被当开启、
            # 下一行被当关闭、正文再被标题剥掉 → 空骨架建议删）。tilde 围栏
            # 的 info string 允许反引号，不受此限。
            if not in_fence and not (tok[0] == "`" and "`" in ln[m.end() :]):
                in_fence, fence_char, fence_len = True, tok[0], len(tok)
                rows.append((ln, "fence"))
                continue
            # ⛔ 关闭围栏 = 同字符 **且长度 ≥ 开启长度、围栏后仅 ASCII 空白**
            # （CommonMark 4.5）。只比字符曾让 ```` 里的 ``` 被当关闭、``` 后带
            # info string 的行也被当关闭 —— 围栏内容 `# keep` 落到围栏外被剥，
            # 整份文件被误判成空骨架 → 建议删（round-2 B3 实证）。
            # ⛔ 「仅空白」必须逐字符限 ASCII 空格/制表符：`str.strip()` 接受一切
            # Unicode 空白，行尾一个 U+00A0（网页复制常见）曾让该行被当成合法
            # 关闭围栏 → 围栏提前闭合 → 建议删（round-3 Codex BLOCKER；NBSP 行
            # 在 CommonMark 里是围栏内容）。
            if (
                tok[0] == fence_char
                and len(tok) >= fence_len
                and all(c in " \t" for c in ln[m.end() :])
            ):
                in_fence, fence_char, fence_len = False, "", 0
                rows.append((ln, "fence"))
                continue
        if in_fence:
            rows.append((ln, "code"))
            continue
        kept, rem = "", ln
        while rem:
            if in_comment:
                i = rem.find("-->")
                if i < 0:
                    break
                rem, in_comment = rem[i + 3 :], False
            else:
                i = rem.find("<!--")
                if i < 0:
                    kept += rem
                    break
                kept += rem[:i]
                rem, in_comment = rem[i + 4 :], True
        rows.append((kept, "text"))
    return rows, in_comment


def _classify_lines(text: str) -> list[tuple[str, bool]]:
    """二态视图（该行是否属围栏区），供 `dup_body` 等逐字保真路径使用。
    三态细节见 `_classify_lines_typed`。"""
    return [(ln, kind != "text") for ln, kind in _classify_lines_typed(text)[0]]


def dup_body(text: str) -> str:
    """**逐字保真**的正文形态 —— C4「精确重复」的唯一比对依据。

    只做无语义的归一：丢标题行（围栏外）、行尾空白 rstrip、丢空行、NFC。
    ⛔ **不** `.strip()` 每行、**不**剥列表符号：那会抹掉代码缩进，让
    `if ok:` + 缩进 `run()` 与 `if ok:` + 顶格 `run()` 判成"逐字相等"，
    进而对一份语义完全不同的文件给出「建议删」（Codex BLOCKER 实证）。
    有后果的提名，依据必须逐字。
    ⛔ 标题不进比对：同一段材料被粘两份时标题常不同（R8 判据 4 说的是「正文高相似」）。
    """
    parts: list[str] = []
    for ln, is_code in _classify_lines(text):
        if not is_code and _HEADING_RE.match(ln):
            continue
        t = ln.rstrip()
        if not t:
            continue
        parts.append(nfc(t))
    return "\n".join(parts)


def has_substantive_content(text: str) -> bool:
    """这份材料有没有**实质正文** —— C3「空 / 空骨架」的唯一依据。

    与 `dup_body` 刻意分家：这里回答「是不是只剩脚手架」，可以激进归一化
    （剥列表符、丢纯结构行）；那里回答「是不是逐字相同」，必须逐字保真。
    合用一个函数正是 Codex BLOCKER 的根因。
    ⛔ 用三态视图：围栏**内容**行（哪怕长得像围栏标记，如 Markdown 围栏语法
    速查里的 ``` 行）都算实质正文；只有状态机标记的分隔行不算
    （round-3 自审 B3-3）。
    """
    for ln, kind in _classify_lines_typed(text)[0]:
        if kind == "code":
            if ln.strip():
                return True  # 围栏内容 = 真实材料（含长得像围栏的行）
            continue
        if kind == "fence":
            continue
        if _HEADING_RE.match(ln):
            continue
        t = _LIST_PREFIX_RE.sub("", ln).strip()
        if t and not _ONLY_STRUCT_RE.match(t):
            return True
    return False


def skeleton_note(text: str, size: int) -> str:
    """空/骨架的**逐项计数**依据 —— 不是「看起来是空的」而是数出来的。

    ⛔ fences 只数围栏**分隔行**（三态视图），围栏内的空行归入句尾的
    「其余皆空行」—— 原先 `sum(... if c)` 把围栏内空行也算进「代码围栏 N 行」，
    与同一句里的「其余皆空行」不构成划分（round-3 自审 B3-5）。
    """
    if size == 0:
        return "0 字节空文件"
    rows = _classify_lines_typed(text)[0]
    headings = sum(1 for ln, k in rows if k == "text" and _HEADING_RE.match(ln))
    struct = sum(
        1 for ln, k in rows if k == "text" and not _HEADING_RE.match(ln) and ln.strip()
    )
    fences = sum(1 for _, k in rows if k == "fence")
    return (
        f"剥离 frontmatter / HTML 注释后实质正文 0 字符"
        f"（{size} 字节文件：标题 {headings} 行、纯结构行 {struct} 行、"
        f"代码围栏 {fences} 行、其余皆空行或注释）"
    )


def head_window(text: str) -> list[tuple[int, str]]:
    """C2 扫描窗口：frontmatter 行 + 其后前 HEAD_SCAN_LINES 行；返回 (1-based 行号, 原文)。"""
    lines = text.splitlines()
    n = frontmatter_span(lines)
    win: list[tuple[int, str]] = [(i + 1, lines[i]) for i in range(min(n, len(lines)))]
    for j, ln in enumerate(lines[n : n + HEAD_SCAN_LINES]):
        win.append((n + j + 1, ln))
    return win


def _norm_ai_line(ln: str) -> str:
    """AI 标记匹配前的行归一：连续空白（含 NBSP 等一切 Unicode 空白）折叠为
    单空格 + casefold。⛔ 大小写/空白变体曾穿透字面量表与裸子串护栏的双层 ——
    `generated by ai`（全小写）、`GENERATED BY AI`、内部 NBSP 形态都曾在无正文
    时掉进 C3 建议删（round-5 审查 BLOCKER-1）。归一化是确定性的，二跑逐字节
    相等不受影响；basis 里的标记文本以归一化形态呈现，行号仍准确。"""
    return " ".join(ln.split()).casefold()


#: 归一化后的标记表（模块级算一次；全大写字母 ascii_ending 判定与原表一致）。
_AI_MARKERS_NORM = tuple(" ".join(m.split()).casefold() for m in AI_MARKERS)

#: ⛔ 护栏级 AI 信号（结构性，不依赖枚举表）：文本含独立「AI」字样即算嫌疑。
#: 「独立」= 左右都**不是 ASCII 字母**（`\bAI\b` 在 CJK 邻接时无词边界 ——
#: round-7 BLOCKER-1：`由AI系统生成` 曾穿透）。有限标记表无论怎么扩都追不上
#: 自然语言的肯定式声明（round-6 BLOCKER-1：`This report was generated by an
#: AI system` 不含任何表项，双层全盲，无正文时掉进 C3 建议删）。本信号只降
#: C6 不裁决 —— C2 确定命中仍走有限表 + 边界规则（宽匹配会给话题提及发确定
#: 归档，那是硬猜）。
_AI_WORD_RE = re.compile(r"(?<![A-Za-z])AI(?![A-Za-z])", re.IGNORECASE)


def _find_marker_pos(ln: str, marker: str) -> int:
    """marker 在**已归一**的 ln 中第一个满足右边界规则的起点；无则 -1。

    ⛔ 右边界 = 行尾、空白或 `_MARKER_BOUNDARY_PUNCT` 标点（round-2 H2）：裸子串
    匹配曾把 `# 由 AI 生成内容的版权问题` 这类话题提及判成 AI 自述并给出确定的
    归档去向。同一行里前一处命中不满足边界时继续向后找 —— 不因首处被拒就漏掉
    行内更靠后的真命中。
    ⛔ 以 ASCII 字母收尾的标记（`Generated by AI`）右边界**不含空白**：中英混排里
    ASCII 词后天然是空格，放行空白等于边界规则对这些标记是空操作 ——
    `Generated by AI Lab researchers` 会被误判成 AI 自述（round-3 自审 H2-1）。
    只认行尾或标点；漏判方向落 C6，安全。"""
    ascii_ending = marker[-1].isascii() and marker[-1].isalpha()
    start = 0
    while (i := ln.find(marker, start)) >= 0:
        j = i + len(marker)
        if j >= len(ln) or ln[j] in _MARKER_BOUNDARY_PUNCT:
            return i
        if not ascii_ending and ln[j].isspace():
            return i
        start = i + 1
    return -1


def find_ai_marker(text: str) -> tuple[int, str] | None:
    """文头窗口内的 AI 标记（归一化匹配：大小写/空白变体不漏，round-5 BLOCKER-1；
    右边界规则见 `_find_marker_pos`）。同行多命中时取「最靠前、同位置取最长」。
    ⛔ 返回的 marker 是**原表原文**（供 basis 逐字展示），匹配在归一化形态上做
    —— 行号准确，文本保真。"""
    for lineno, ln in head_window(text):
        norm = _norm_ai_line(ln)
        hits = [
            (pos, -len(nm), orig)
            for nm, orig in zip(_AI_MARKERS_NORM, AI_MARKERS)
            if (pos := _find_marker_pos(norm, nm)) >= 0
        ]
        if hits:
            _, _, marker = min(hits)
            return lineno, marker
    return None


def raw_ai_marker(text: str) -> str | None:
    """文头窗口内的**裸子串** AI 字样（归一化匹配，不做边界检查）—— 只用作
    C3/C4 的「未消化信号」，不作 C2 判据。边界规则拒掉的命中（如 `Generated
    by AI on March`）说明这行有 AI 自述嫌疑但引擎不敢确定；这样的文件若又
    没有实质正文，判「空骨架建议删」就是把嫌疑当垃圾扔（round-4 BLOCKER-1）。
    返回原表原文（uncertain_reason 展示用）。"""
    for _, ln in head_window(text):
        norm = _norm_ai_line(ln)
        for nm, orig in zip(_AI_MARKERS_NORM, AI_MARKERS):
            if nm in norm:
                return orig
    return None


def round_of(name: str) -> str | None:
    m = _ROUND_RE.search(name)
    return m.group(1) if m else None


def round_type(name: str) -> str | None:
    for pat, typ in ROUND_SUBPATTERNS:
        if pat in name:
            return typ
    return None


# ───────────────────────────── 扫描 ─────────────────────────────


def read_text_or_none(p: Path) -> str | None:
    try:
        return p.read_bytes().decode("utf-8")
    except (OSError, UnicodeDecodeError):
        return None


def scan_corpus(
    vault: Path, excluded_roots: list[str]
) -> tuple[dict[str, list[str]], list[tuple[str, str]], dict]:
    """库内 .md 语料：→ (归一化正文 → [相对路径…], [(路径, 正文)…], 统计)。

    排除：一切隐藏目录、`outputs/`、收件箱子树、产物目录子树。
    ⛔ **空正文不进重复索引** —— 否则库内任意两个空骨架互为「正本」，会撑出一条
    有后果的建议删，其证据是「两个都是空的」。C3 虽然先命中，但索引本身必须先干净：
    门要防的是未来次序调整时的静默失效，不只是当下这一次。
    """
    by_body: dict[str, list[str]] = {}
    bodies: list[tuple[str, str]] = []
    stats = {
        "files_scanned": 0,
        "files_indexed": 0,
        "skipped_empty_body": 0,
        "skipped_symlink": 0,
        "skipped_unreadable": 0,
        "truncated": False,
        "file_cap": CORPUS_FILE_CAP,
    }
    for dirpath, dirnames, filenames in os.walk(vault):
        dirnames[:] = sorted(
            d
            for d in dirnames
            if not d.startswith(".")
            and d not in CORPUS_EXCLUDED_DIR_NAMES
            and os.path.realpath(os.path.join(dirpath, d)) not in excluded_roots
        )
        for fn in sorted(filenames):
            if not fn.endswith(".md"):
                continue
            if stats["files_scanned"] >= CORPUS_FILE_CAP:
                # ⛔ 不在此处 return —— 早退会绕过下面的排序尾巴, 让"截断"与"未截断"
                # 两条路径产出形态不同的索引。置位后跳出全部循环, 走同一个出口。
                stats["truncated"] = True
                dirnames.clear()
                break
            p = Path(dirpath) / fn
            stats["files_scanned"] += 1
            if p.is_symlink():
                stats["skipped_symlink"] += 1
                continue
            text = read_text_or_none(p)
            if text is None:
                stats["skipped_unreadable"] += 1
                continue
            if not has_substantive_content(text):
                stats["skipped_empty_body"] += 1
                continue
            body = dup_body(text)
            if not body:
                stats["skipped_empty_body"] += 1
                continue
            rel = p.relative_to(vault).as_posix()
            by_body.setdefault(body, []).append(rel)
            bodies.append((rel, body))
            stats["files_indexed"] += 1
        if stats["truncated"]:
            break
    for v in by_body.values():
        v.sort()
    bodies.sort()
    return by_body, bodies, stats


def near_duplicates(
    body: str, corpus_bodies: list[tuple[str, str]], scan: dict
) -> list[dict]:
    """difflib 近似（按行比对）。⛔ 只标疑似，永不裁决 —— 见显式偏差 1。"""
    if not body:
        return []
    a_lines = body.split("\n")
    la = len(body)
    hits: list[tuple[float, str]] = []
    for rel, other in corpus_bodies:
        if other == body:
            continue  # 逐字相等归 C4，不重复计入疑似
        lb = len(other)
        if la > NEAR_DUP_BODY_CHAR_CAP or lb > NEAR_DUP_BODY_CHAR_CAP:
            scan["skipped_oversize"] += 1
            continue
        if not (1 / NEAR_DUP_LEN_RATIO <= (lb / la if la else 0) <= NEAR_DUP_LEN_RATIO):
            scan["skipped_length_prefilter"] += 1
            continue
        scan["compared_pairs"] += 1
        sm = difflib.SequenceMatcher(None, a_lines, other.split("\n"), autojunk=False)
        if sm.real_quick_ratio() < NEAR_DUP_RATIO or sm.quick_ratio() < NEAR_DUP_RATIO:
            continue
        r = sm.ratio()
        if r >= NEAR_DUP_RATIO:
            hits.append((r, rel))
    hits.sort(key=lambda x: (-x[0], x[1]))
    return [{"path": rel, "ratio": round(r, 4)} for r, rel in hits[:NEAR_DUP_TOP_N]]


# ───────────────────────── 逐份提名（判据次序即本函数结构） ─────────────────────────


def nominate(
    item: dict,
    text: str | None,
    dup_index: dict[str, list[str]],
    corpus_bodies: list[tuple[str, str]],
    scan: dict,
    batch_body_counts: dict[str, int],
) -> dict:
    """对一件材料出提名。**次序即 CRITERIA_ORDER**，先命中者定 verdict；
    后续判据的证据仍全量附上（conflicts / exact_duplicate_of / near_duplicates）。"""
    name = item["name"]
    conflicts: list[dict] = []

    if text is None:
        # 非 UTF-8（PDF/图片等）：除 0 字节外无任何可机械判读的信号 → 不猜。
        if item["size_bytes"] == 0:
            return _fill(
                item,
                "C3_empty_or_skeleton",
                V_DELETE,
                None,
                None,
                "0 字节空文件",
                True,
                conflicts=conflicts,
            )
        return _fill(
            item,
            "C6_undecided",
            V_UNSURE,
            None,
            None,
            "非 UTF-8 文本，本引擎不解析其正文",
            False,
            uncertain_reason="非 UTF-8 文本（如 PDF / 图片），六判据中除「0 字节」外无一可施加",
            ask=UNDECIDED_ASK,
            conflicts=conflicts,
        )

    fm_lines = split_frontmatter(text)[0]
    fm = frontmatter_map(fm_lines)
    typed_rows, unclosed_comment = _classify_lines_typed(text)
    del typed_rows
    substantive = has_substantive_content(text)
    body = dup_body(text) if substantive else ""
    rnd = round_of(name)
    # C3 护栏信号（显式偏差 15）：frontmatter 里「看着像键但不被键正则认」的行。
    unparsed_fm = [
        ln.strip()
        for ln in fm_lines
        if ln.strip() and not ln.strip().startswith("#") and not _FM_KEY_RE.match(ln)
    ]
    # 未消化信号之四：边界规则拒掉的 AI 自述嫌疑（裸子串在场即算，见 raw_ai_marker）。
    ai_suspect = raw_ai_marker(text)
    # 未消化信号之六（round-6 BLOCKER-1）：独立词「AI」结构性信号 —— 不依赖
    # 枚举表，frontmatter 值或文头任一行含独立词 AI 即算嫌疑。
    ai_word_hit = next(
        (
            v
            for v in [*fm.values(), *[ln for _, ln in head_window(text)]]
            if _AI_WORD_RE.search(v)
        ),
        None,
    )

    # ── 后置证据（不参与次序，但必须全量呈现） ──
    exact_all = sorted(dup_index.get(body, [])) if body else []
    exact_of = exact_all[0] if exact_all else None
    exact_others = exact_all[1:]
    near = near_duplicates(body, corpus_bodies, scan)
    within_batch = bool(body) and batch_body_counts.get(body, 0) > 1
    if within_batch:
        conflicts.append(
            {
                "kind": "duplicate_within_batch",
                "detail": "本批内另有正文逐字相同的材料 —— 谁是正本在只读侧不可判，"
                "故不产出建议删，请你指定保留哪一份",
            }
        )

    def finish(criterion, verdict, ntype, target, basis, confident, **kw):
        if exact_of and criterion != "C4_exact_duplicate":
            conflicts.append(
                {
                    "kind": "exact_duplicate_under_other_verdict",
                    "detail": f"正文与 {exact_of} 逐字相同，但按判据次序本件归 {criterion}"
                    "（次序不因重复而改变，证据在此留痕）",
                }
            )
        if near and criterion != "C6_undecided":
            conflicts.append(
                {
                    "kind": "near_duplicate_suspected",
                    "detail": "疑似与 "
                    + "、".join(f"{n['path']}(ratio {n['ratio']})" for n in near)
                    + " 高相似 —— 疑似不改提名、更不建议删，需你一句话确认",
                }
            )
        return _fill(
            item,
            criterion,
            verdict,
            ntype,
            target,
            basis,
            confident,
            exact_of=exact_of,
            exact_others=exact_others,
            near=near,
            conflicts=conflicts,
            **kw,
        )

    # ── C1 source URL ──
    src = fm.get("source", "")
    if src and _is_primary_source_url(src):
        return finish(
            "C1_source_url",
            V_STAY,
            "primary-record",
            None,
            f"frontmatter source 为一手 URL：{src}",
            True,
        )

    # ── C2 AI 自述 ──
    hit = find_ai_marker(text)
    if hit:
        lineno, marker = hit
        target = f"R{rnd}/" if rnd else DR_TARGET
        return finish(
            "C2_ai_self_declared",
            V_ARCHIVE,
            "secondary-synthesis",
            target,
            f"文头第 {lineno} 行自述「{marker}」"
            + (f"；文件名带 R{rnd}_ 故归轮次目录" if rnd else ""),
            True,
        )

    def _looks_like_source_value(v: str) -> bool:
        """来源声明判定（⛔ substring 级，不要求可机判合法）：值内**任意位置**
        含 `http://` 或 `https://` 即算 —— 前缀判定曾连环穿透：损坏 URL
        （`https://:443/x`，round-5）、autolink 角括号（`<https://…>`，round-6）、
        YAML 标签（`!!str https://…`）与引号包 Markdown 链接（`"[来源](https://…)"`
        —— round-7 BLOCKER-3）。大小写不敏感。"""
        t = v.casefold()
        return "http://" in t or "https://" in t

    # 信号③b：非 source 键名但值是 URL 形态（url:/URL:/Source: 等剪藏工具
    # 常见键名 —— round-5 自审 F2 实证它们曾穿透全部信号被建议删且 URL 零留痕；
    # 值损坏的别名见 `_looks_like_source_value`）。
    # 合法 source 键在此不可能出现（C1 已先行返回）。⚠️ C1 仍只认字面 source 键
    # （R8 稿约定）；本信号只把这类来源摆上台面降 C6，不扩大 C1。
    url_bearing_keys = [k for k, v in fm.items() if v and _looks_like_source_value(v)]

    def undigested_reason() -> str | None:
        """⛔ 「未消化信号」统一护栏（显式偏差 15）：C3/C4 是仅有的两个产出
        「建议删」的判据，命中时若文件带有引擎未能完全消化的结构信号 ——
        未闭合注释 / 解析不成的 frontmatter 行 / 来源声明（source 键或任意
        URL 形态键值）/ 睡眠台账键 / AI 自述嫌疑 —— 一律降 C6 拿不准。
        判据收窄漏掉的文件曾掉进这两个判据被建议删（round-3 自审 H1-1/H3-1 +
        round-4 BLOCKER-1/BLOCKER-2 + round-5 自审 F2/F3 实证）；
        「安全」是路径属性：必须拦在两个出口，而不是只拦 C3。"""
        if unclosed_comment:
            return "文件以未闭合的 HTML 注释结尾（`<!--` 没等到 `-->`），哪些内容被吞掉引擎猜不了"
        if unparsed_fm:
            return (
                f"frontmatter 含本引擎无法解析为键的行（如 {unparsed_fm[0]!r}），"
                "解析不完整"
            )
        if "source" in fm:
            return (
                f"frontmatter 声明了 source（{fm['source']!r}）但不是可机判的"
                "一手 URL —— 来源声明还在，不能当它不存在"
            )
        if url_bearing_keys:
            return (
                f"frontmatter 的 {url_bearing_keys[0]} 键声明了一个来源 URL"
                f"（{fm[url_bearing_keys[0]]!r}）—— 来源声明还在，不能当它不存在"
            )
        if "slept_at" in fm:
            return (
                f"frontmatter 带睡眠台账键 slept_at（{fm['slept_at']!r}）—— "
                "它记录着这份材料的起睡时间（引擎在 Sleeping 台账里认识这个键），"
                "删除会把台账状态一起抹掉"
            )
        if ai_suspect:
            return (
                f"文头有疑似 AI 生成自述（「{ai_suspect}」）但按边界规则不构成"
                "确定命中 —— 是自述还是话题提及，引擎拿不准"
            )
        if ai_word_hit:
            return (
                f"文头或 frontmatter 出现独立词「AI」（如 {ai_word_hit!r}），"
                "可能与 AI 生成有关 —— 引擎不解读语义，宁可拿不准"
            )
        return None

    # ── C3 空 / 空骨架（⛔ 未消化信号护栏，见显式偏差 15）──
    if not substantive:
        signal = undigested_reason()
        if signal:
            return finish(
                "C6_undecided",
                V_UNSURE,
                None,
                None,
                "无机械判据可施加",
                False,
                uncertain_reason=(
                    f"{signal}，文件又没有实质正文 —— 是空骨架还是「信号还没被"
                    "读懂的文件」拿不准，不敢建议删"
                ),
                ask=UNDECIDED_ASK,
            )
        return finish(
            "C3_empty_or_skeleton",
            V_DELETE,
            None,
            None,
            skeleton_note(text, item["size_bytes"]),
            True,
        )

    # ── C4 精确重复（**逐字相等**才算；近似永不到这里） ──
    # ⛔ 批内也有同稿时**不再**否决 C4（Codex MEDIUM 实证）：只要库内已经有一份
    # 逐字相同的，收件箱这份就是多余的 —— 与批内还有几份同稿无关。
    # ⛔ 未消化信号护栏同样拦 C4（round-4 BLOCKER-2）：C4 只证明「剥掉
    # frontmatter 后正文相等」，不证明「整个文件多余」——带 source 声明等
    # 信号的文件被建议删时信号必须先摆到台面上，删不删由人定。
    if exact_of:
        signal = undigested_reason()
        if signal:
            return finish(
                "C6_undecided",
                V_UNSURE,
                None,
                None,
                "无机械判据可施加",
                False,
                uncertain_reason=(
                    f"{signal}；且正文与 {exact_of} 逐字相同 —— 但「整个文件"
                    "多余」只有正文证据支撑，上述信号未消化，删不删由你定"
                ),
                ask=UNDECIDED_ASK,
            )
        if fm:
            # ⛔ round-5 自审：C4 的正文证据不覆盖 frontmatter 元数据（tags/created
            # 等引擎不消费的键）。不降级（重复多余性成立），但元数据存在必须留痕
            # —— 删除是不可逆执行，痕迹是人的最后一道核对面。
            conflicts.append(
                {
                    "kind": "frontmatter_metadata_present",
                    "detail": "本件 frontmatter 还带有元数据键（"
                    + "、".join(sorted(fm))
                    + "），正文重复证据不覆盖它们 —— 执行删除前请过目",
                }
            )
        if exact_others:
            basis = (
                f"库内已有 {len(exact_all)} 份正文逐字相同的文件："
                + "、".join(exact_all)
                + "。⛔ 哪一份算「正本」不可判（无机械依据），"
                "但收件箱这份相对它们是多余的，故仍建议删"
            )
            conflicts.append(
                {
                    "kind": "multiple_canonical_candidates",
                    "detail": f"库内有 {len(exact_all)} 份同正文文件，"
                    f"`exact_duplicate_of` 取相对路径字典序最小者仅为**可预测的代表**，"
                    "不主张它比其余几份更正本",
                }
            )
        else:
            basis = f"归一化正文与 {exact_of} 逐字相等（sha256 相同）"
        return finish("C4_exact_duplicate", V_DELETE, None, None, basis, True)

    # ── C5 R{n}_ 文件名 ──
    if rnd:
        typ = round_type(name)
        return finish(
            "C5_round_filename",
            V_ARCHIVE,
            typ,
            f"R{rnd}/",
            f"文件名带 R{rnd}_ → 归轮次目录"
            + (
                f"；子模式命中 → 类型 {typ}"
                if typ
                else "；子模式未命中 → 类型留空（去向确定，类型拿不准，不硬填）"
            ),
            True,
            type_uncertain=typ is None,
        )

    # ── C6 兜底：拿不准（不给去向、不给类型） ──
    if within_batch:
        reason = "本批内有正文逐字相同的另一件，谁是正本不可判 —— 不硬猜"
    elif near:
        reason = (
            "疑似与 "
            + "、".join(f"{n['path']}(ratio {n['ratio']})" for n in near)
            + " 高相似，但**未逐字相等** —— 近似不等于重复，不硬猜"
        )
    else:
        reason = (
            "六判据全不命中：无 source URL、文头无可确定的 AI 自述、有实质正文、"
            "与库内无逐字相同正本、文件名无 R{n}_ 轮次标记"
        )
    if ai_suspect:
        # 嫌疑提示对 within_batch / near / 全不命中三个分支统一补挂 ——
        # round-5 自审 F6：只挂在 else 曾让「批内重复 + AI 嫌疑」件的理由缺嫌疑面。
        reason += f"；文头有「{ai_suspect}」字样但按边界规则不算确定自述，请你过目定夺"
    return finish(
        "C6_undecided",
        V_UNSURE,
        None,
        None,
        "无机械判据可施加",
        False,
        uncertain_reason=reason,
        ask=UNDECIDED_ASK,
    )


def _fill(
    item: dict,
    criterion: str,
    verdict: str,
    ntype: str | None,
    target: str | None,
    basis: str,
    confident: bool,
    *,
    uncertain_reason: str | None = None,
    ask: str | None = None,
    type_uncertain: bool = False,
    exact_of: str | None = None,
    exact_others: list[str] | None = None,
    near: list[dict] | None = None,
    conflicts: list[dict] | None = None,
) -> dict:
    out = dict(item)
    out.update(
        {
            "criterion": criterion,
            "verdict": verdict,
            "nomination_type": ntype,
            "target_hint": target,
            "basis": basis,
            "confident": confident,
            "type_uncertain": type_uncertain,
            "uncertain_reason": uncertain_reason,
            "ask": ask,
            "exact_duplicate_of": exact_of,
            "exact_duplicate_others": exact_others or [],
            "near_duplicates": near or [],
            "conflicts": conflicts or [],
        }
    )
    return out



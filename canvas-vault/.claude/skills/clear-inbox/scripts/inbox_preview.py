#: ATX 标题：**最多 3 个字面空格**缩进（⛔ 与 _FENCE_RE 同口径，\s 会放行
#: 制表符/NBSP —— `\t# keep` 是缩进代码、`\xa0# keep` 是普通正文，都曾被当
#: 标题剥掉 → 空骨架建议删，round-7 BLOCKER-2）。
_HEADING_RE = re.compile(r"^ {0,3}#{1,6}(?:\s|$)")
_LIST_PREFIX_RE = re.compile(r"^\s*(?:[-*+]\s+|\d{1,3}[.)]\s+|>\s?)+")
#: 纯结构行（分隔线 / 表格分隔 / 空列表符）。⛔ 不含 `~`：`~~~` 是代码围栏标记，

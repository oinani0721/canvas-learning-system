_FENCE_RE = re.compile(r"^ {0,3}(`{3,}|~{3,})")
#: ⛔ YAML 映射键必须是 `key:` 后接**空白或行尾**：正文行 `http://example.com/path`
#: 里的 `http:` 曾被当成键，整篇被吞成 frontmatter → 空骨架 → 建议删（round-2 H3）。
#: 连带：`source:https://x`（冒号后无空格）此后不再识别为键 —— 若它是块内首个有效
#: 行则整块降为正文，否则被 span 吞掉；两种形态都由 C3 护栏（显式偏差 15）兜住落 C6。
#: 冒号前允许空白（`title : x` 与 `_FM_LOOKS_LIKE_KEY_RE` 同口径，pyyaml 亦认它是键；
#: round-3 自审 H3-3：两条正则曾对「什么算键」各说各话，span 认而 map 不认 → 空正文）。
_FM_KEY_RE = re.compile(r"^([A-Za-z_][A-Za-z0-9_-]*)\s*:(?:\s+(.*))?\s*$")
#: frontmatter 首个有效行必须像 YAML 映射键 —— 否则那只是被两条 `---` 夹住的正文
_FM_LOOKS_LIKE_KEY_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_-]*\s*:(?:\s|$)")
#: URL 形状初筛（`https?://\S+` 会把 `https://?` 也认成一手来源，Codex HIGH）。
#: ⛔ 但正则列不尽 authority 段的空 host 形态（`https://:443/x`、`https://user@/x`
#: 都能过它）——host 非空由 `_is_primary_source_url` 的 urlsplit 检查保证
#: （round-2 H1 实证），本正则只负责拦明显不是 URL 的值。
#: re.I：URI scheme 按 RFC 3986 §3.1 大小写不敏感，`HTTPS://example.com` 也是
#: 一手来源（round-3 自审 H1-2）；大小写归一后 scheme 检查在 `_is_primary_source_url`
#: 里仍保留作防御深度。
_URL_RE = re.compile(r"^https?://[^\s/?#]+\S*$", re.IGNORECASE)


def _is_primary_source_url(src: str) -> bool:
    """C1 的机械判据：`scheme ∈ {http, https}` **且 hostname 非空**才算一手来源。
    解析异常一律不算 URL —— 方向安全（不误判一手，材料落后续判据）。"""
    if not _URL_RE.match(src):
        return False
    try:
        parts = urlsplit(src)
    except ValueError:
        return False
    return parts.scheme in ("http", "https") and bool(parts.hostname)


